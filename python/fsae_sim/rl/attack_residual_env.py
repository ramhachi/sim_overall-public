"""Black-box residual profile environment for the attack driver.

The environment treats one full laptime run as one episode.  The action is a
fixed-course residual profile sampled at a small number of station knots:

``[dv_0, dsteer_0, dv_1, dsteer_1, ...]`` in normalized ``[-1, 1]`` units.

This is intentionally a light wrapper around ``cpp/laptime_sim``.  It avoids
binding the training pipeline to C++ internals and keeps the residual policy
portable across Python RL libraries.
"""

from __future__ import annotations

import csv
import json
import math
import re
import shutil
import subprocess
import tempfile
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Mapping, Optional, Sequence

import numpy as np

JSON_BLOCK_RE = re.compile(r"%%JSON_BEGIN%%\s*(\{.*?\})\s*%%JSON_END%%", re.S)


@dataclass(frozen=True)
class AttackRunResult:
    """Result and diagnostics from one residual-profile laptime run."""

    reward: float
    lap_completed: bool
    lap_time: float
    distance_traveled: float
    max_track_limit_excess: float
    mpc_fail_count: int
    csv_path: Path
    profile_path: Path
    stdout_path: Path
    stderr_path: Path
    json_result: dict[str, Any] = field(default_factory=dict)
    analysis: dict[str, Any] = field(default_factory=dict)


@dataclass(frozen=True)
class AttackResidualEnvConfig:
    """Configuration for residual-profile attack-driver training."""

    executable: Path
    repo_root: Path
    out_dir: Path
    track: str = "autocross"
    params_file: Path | None = None
    time_limit_s: float = 120.0
    driver_torque_max_nm: float = 40.0
    knot_count: int = 64
    track_length_m: float = 1000.0
    max_delta_v_ref_mps: float = 2.0
    max_delta_steer_ff_rad: float = 0.035
    action_smoothing_passes: int = 0
    lap_time_target_s: float = 66.0
    fail_reward_distance_scale: float = 0.02
    track_excess_penalty: float = 250.0
    mpc_fail_penalty: float = 25.0
    command_extra_args: tuple[str, ...] = ()


RunCallable = Callable[[Sequence[str], Path, Optional[float]], subprocess.CompletedProcess[str]]
AnalyzeCallable = Callable[[Path], dict[str, Any]]


def _clip01_action(action: Sequence[float]) -> np.ndarray:
    values = np.asarray(action, dtype=np.float64).reshape(-1)
    if not np.all(np.isfinite(values)):
        raise ValueError("residual action contains non-finite values")
    return np.clip(values, -1.0, 1.0)


def _smooth_pairs(pairs: np.ndarray, passes: int) -> np.ndarray:
    smoothed = np.array(pairs, dtype=np.float64, copy=True)
    for _ in range(max(0, passes)):
        if len(smoothed) <= 2:
            break
        previous = np.roll(smoothed, 1, axis=0)
        next_ = np.roll(smoothed, -1, axis=0)
        smoothed = 0.25 * previous + 0.50 * smoothed + 0.25 * next_
    return smoothed


def action_to_profile(
    action: Sequence[float],
    *,
    knot_count: int,
    track_length_m: float,
    max_delta_v_ref_mps: float = 2.0,
    max_delta_steer_ff_rad: float = 0.035,
    smoothing_passes: int = 0,
    description: str = "Residual profile generated by Python attack residual RL.",
) -> dict[str, Any]:
    """Convert a normalized residual action vector into C++ profile JSON."""

    if knot_count <= 0:
        raise ValueError("knot_count must be positive")
    if track_length_m <= 0.0:
        raise ValueError("track_length_m must be positive")
    expected_dim = 2 * knot_count
    values = _clip01_action(action)
    if values.size != expected_dim:
        raise ValueError(f"expected action dimension {expected_dim}, got {values.size}")

    pairs = values.reshape(knot_count, 2)
    pairs = _smooth_pairs(pairs, smoothing_passes)
    stations = np.linspace(0.0, track_length_m, knot_count, endpoint=False)
    samples = []
    for station, pair in zip(stations, pairs):
        samples.append(
            {
                "s": float(station),
                "delta_v_ref_mps": float(pair[0] * max_delta_v_ref_mps),
                "delta_steer_ff_rad": float(pair[1] * max_delta_steer_ff_rad),
            }
        )

    return {
        "schema": "attack_residual_profile_v1",
        "description": description,
        "limits": {
            "max_delta_v_ref_mps": float(abs(max_delta_v_ref_mps)),
            "max_delta_steer_ff_rad": float(abs(max_delta_steer_ff_rad)),
        },
        "samples": samples,
        "metadata": {
            "generator": "python/fsae_sim/rl/attack_residual_env.py",
            "knot_count": knot_count,
            "track_length_m": float(track_length_m),
            "action_smoothing_passes": max(0, int(smoothing_passes)),
        },
    }


def profile_to_action(
    profile: Mapping[str, Any],
    *,
    knot_count: int,
    track_length_m: float,
    max_delta_v_ref_mps: float = 2.0,
    max_delta_steer_ff_rad: float = 0.035,
) -> np.ndarray:
    """Project a residual profile onto the normalized action grid."""

    if knot_count <= 0:
        raise ValueError("knot_count must be positive")
    samples = sorted(profile.get("samples", []), key=lambda item: float(item.get("s", 0.0)))
    if not samples:
        return np.zeros(2 * knot_count, dtype=np.float64)

    stations = np.linspace(0.0, track_length_m, knot_count, endpoint=False)
    sample_s = np.asarray([float(item.get("s", item.get("s_m", 0.0))) for item in samples])
    sample_v = np.asarray(
        [
            float(item.get("delta_v_ref_mps", item.get("delta_v_mps", 0.0)))
            for item in samples
        ]
    )
    sample_steer = np.asarray(
        [
            float(item.get("delta_steer_ff_rad", item.get("delta_steer_rad", 0.0)))
            for item in samples
        ]
    )
    delta_v = np.interp(stations, sample_s, sample_v, left=sample_v[0], right=sample_v[-1])
    delta_steer = np.interp(
        stations,
        sample_s,
        sample_steer,
        left=sample_steer[0],
        right=sample_steer[-1],
    )
    action = np.empty(2 * knot_count, dtype=np.float64)
    action[0::2] = delta_v / max(max_delta_v_ref_mps, 1e-9)
    action[1::2] = delta_steer / max(max_delta_steer_ff_rad, 1e-9)
    return np.clip(action, -1.0, 1.0)


def _extract_json_result(stdout: str) -> dict[str, Any]:
    match = JSON_BLOCK_RE.search(stdout)
    if not match:
        return {}
    try:
        return json.loads(match.group(1))
    except json.JSONDecodeError:
        return {}


def _finite_float(value: Any, default: float = math.nan) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return default
    return number if math.isfinite(number) else default


def _bool_result(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"1", "true", "yes", "completed"}


def _default_run(
    cmd: Sequence[str],
    cwd: Path,
    timeout: float | None,
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            list(cmd),
            cwd=cwd,
            text=True,
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        stdout = exc.stdout or ""
        stderr = exc.stderr or ""
        if isinstance(stdout, bytes):
            stdout = stdout.decode(errors="replace")
        if isinstance(stderr, bytes):
            stderr = stderr.decode(errors="replace")
        stderr = (
            str(stderr)
            + f"\nTIMEOUT: command exceeded {timeout} seconds: {' '.join(map(str, cmd))}\n"
        )
        return subprocess.CompletedProcess(list(cmd), 124, stdout=str(stdout), stderr=stderr)


def _mean_csv_column(csv_path: Path, column: str) -> float | None:
    values: list[float] = []
    if not csv_path.exists():
        return None
    with csv_path.open(newline="") as handle:
        for row in csv.DictReader(handle):
            try:
                value = float(row.get(column, ""))
            except (TypeError, ValueError):
                continue
            if math.isfinite(value):
                values.append(value)
    if not values:
        return None
    return sum(values) / len(values)


def _default_analyze(csv_path: Path) -> dict[str, Any]:
    return {
        "mean_speed_mps": _mean_csv_column(csv_path, "speed"),
        "mean_course_target_gap_mps": _mean_csv_column(csv_path, "course_target_gap"),
    }


class AttackResidualProfileEnv:
    """One-step black-box environment around ``laptime_sim --driver attack``."""

    def __init__(
        self,
        config: AttackResidualEnvConfig,
        *,
        run_command: RunCallable | None = None,
        analyze_csv: AnalyzeCallable | None = None,
        timeout_s: float | None = None,
    ) -> None:
        self.config = config
        self.run_command = run_command or _default_run
        self.analyze_csv = analyze_csv or _default_analyze
        self.timeout_s = timeout_s
        self.last_result: AttackRunResult | None = None
        self.config.out_dir.mkdir(parents=True, exist_ok=True)

    @property
    def action_dim(self) -> int:
        return 2 * self.config.knot_count

    def reset(self, seed: int | None = None) -> tuple[np.ndarray, dict[str, Any]]:
        if seed is not None:
            np.random.default_rng(seed)
        return self._observation_from_result(None), {"action_dim": self.action_dim}

    def step(
        self,
        action: Sequence[float],
    ) -> tuple[np.ndarray, float, bool, bool, dict[str, Any]]:
        result = self.evaluate_action(action)
        self.last_result = result
        observation = self._observation_from_result(result)
        info = {
            "lap_completed": result.lap_completed,
            "lap_time": result.lap_time,
            "distance_traveled": result.distance_traveled,
            "max_track_limit_excess": result.max_track_limit_excess,
            "mpc_fail_count": result.mpc_fail_count,
            "csv_path": str(result.csv_path),
            "profile_path": str(result.profile_path),
            "analysis": result.analysis,
        }
        return observation, result.reward, True, False, info

    def evaluate_action(self, action: Sequence[float]) -> AttackRunResult:
        run_id = uuid.uuid4().hex[:12]
        run_dir = self.config.out_dir / f"episode_{run_id}"
        run_dir.mkdir(parents=True, exist_ok=True)
        profile_path = run_dir / "residual_profile.json"

        profile = action_to_profile(
            action,
            knot_count=self.config.knot_count,
            track_length_m=self.config.track_length_m,
            max_delta_v_ref_mps=self.config.max_delta_v_ref_mps,
            max_delta_steer_ff_rad=self.config.max_delta_steer_ff_rad,
            smoothing_passes=self.config.action_smoothing_passes,
        )
        profile_path.write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
        return self._evaluate_profile_path(profile_path, run_dir)

    def evaluate_profile_file(self, profile_file: Path) -> AttackRunResult:
        """Evaluate an existing residual profile without resampling it first."""

        run_id = uuid.uuid4().hex[:12]
        run_dir = self.config.out_dir / f"episode_{run_id}"
        run_dir.mkdir(parents=True, exist_ok=True)
        profile_path = run_dir / "residual_profile.json"
        shutil.copyfile(profile_file, profile_path)
        return self._evaluate_profile_path(profile_path, run_dir)

    def evaluate_profile_dict(self, profile: Mapping[str, Any]) -> AttackRunResult:
        """Evaluate an already materialized residual profile JSON object."""

        run_id = uuid.uuid4().hex[:12]
        run_dir = self.config.out_dir / f"episode_{run_id}"
        run_dir.mkdir(parents=True, exist_ok=True)
        profile_path = run_dir / "residual_profile.json"
        profile_path.write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
        return self._evaluate_profile_path(profile_path, run_dir)

    def _evaluate_profile_path(self, profile_path: Path, run_dir: Path) -> AttackRunResult:
        csv_path = run_dir / "laptime.csv"
        stdout_path = run_dir / "stdout.txt"
        stderr_path = run_dir / "stderr.txt"
        cmd = [
            str(self.config.executable),
            "--track",
            self.config.track,
            "--driver",
            "attack",
            "--time",
            f"{self.config.time_limit_s:.12g}",
            "--driver-torque-max",
            f"{self.config.driver_torque_max_nm:.12g}",
            "--attack-residual-profile",
            str(profile_path),
            "--output",
            str(csv_path),
            "--output_json",
            *self.config.command_extra_args,
        ]
        if self.config.params_file is not None:
            cmd.extend(["--params_file", str(self.config.params_file)])

        completed = self.run_command(cmd, self.config.repo_root, self.timeout_s)
        stdout_path.write_text(completed.stdout or "", encoding="utf-8")
        stderr_path.write_text(completed.stderr or "", encoding="utf-8")

        json_result = _extract_json_result(completed.stdout or "")
        analysis = self.analyze_csv(csv_path) if csv_path.exists() else {}
        lap_completed = _bool_result(json_result.get("lap_completed"))
        lap_time = _finite_float(json_result.get("lap_time"))
        distance = _finite_float(json_result.get("distance_traveled"), 0.0)
        max_excess = _finite_float(json_result.get("max_track_limit_excess"), 0.0)
        mpc_fail_count = int(_finite_float(json_result.get("mpc_fail_count"), 0.0))
        reward = self._compute_reward(
            lap_completed=lap_completed,
            lap_time=lap_time,
            distance_traveled=distance,
            max_track_limit_excess=max_excess,
            mpc_fail_count=mpc_fail_count,
            simulation_error=completed.returncode != 0 and not json_result,
        )
        return AttackRunResult(
            reward=reward,
            lap_completed=lap_completed,
            lap_time=lap_time,
            distance_traveled=distance,
            max_track_limit_excess=max_excess,
            mpc_fail_count=mpc_fail_count,
            csv_path=csv_path,
            profile_path=profile_path,
            stdout_path=stdout_path,
            stderr_path=stderr_path,
            json_result=json_result,
            analysis=analysis,
        )

    def _compute_reward(
        self,
        *,
        lap_completed: bool,
        lap_time: float,
        distance_traveled: float,
        max_track_limit_excess: float,
        mpc_fail_count: int,
        simulation_error: bool,
    ) -> float:
        if lap_completed and math.isfinite(lap_time):
            reward = self.config.lap_time_target_s - lap_time
        else:
            reward = (
                -self.config.time_limit_s
                + self.config.fail_reward_distance_scale * distance_traveled
            )
        reward -= self.config.track_excess_penalty * max(0.0, max_track_limit_excess)
        reward -= self.config.mpc_fail_penalty * max(0, mpc_fail_count)
        if simulation_error:
            reward -= 1000.0
        return float(reward)

    @staticmethod
    def _observation_from_result(result: AttackRunResult | None) -> np.ndarray:
        if result is None:
            return np.zeros(8, dtype=np.float32)
        mean_speed = _finite_float(result.analysis.get("mean_speed_mps"), 0.0)
        mean_gap = _finite_float(result.analysis.get("mean_course_target_gap_mps"), 0.0)
        lap_time = result.lap_time if math.isfinite(result.lap_time) else 0.0
        return np.asarray(
            [
                1.0 if result.lap_completed else 0.0,
                lap_time,
                result.distance_traveled,
                result.max_track_limit_excess,
                float(result.mpc_fail_count),
                result.reward,
                mean_speed,
                mean_gap,
            ],
            dtype=np.float32,
        )


def temporary_out_dir(prefix: str = "attack_residual_rl_") -> Path:
    """Create a temporary output directory for command-line training runs."""

    return Path(tempfile.mkdtemp(prefix=prefix))
