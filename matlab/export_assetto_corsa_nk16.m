end

function copyTemplateCarFiles(templateDir, outputDir)
if ~isfolder(templateDir)
    error('TemplateCarDir not found: %s', templateDir);
end

entries = dir(templateDir);
for i = 1:numel(entries)
    name = entries(i).name;
    if strcmp(name, '.') || strcmp(name, '..') || strcmpi(name, 'data') || strcmpi(name, 'data.acd')
        continue;
    end
    copyfile(fullfile(templateDir, name), fullfile(outputDir, name));
end
end

function writePrettyJson(filePath, value)
writeTextFile(filePath, jsonencode(value, 'PrettyPrint', true));
end

function writeTextFile(filePath, content)
dirPath = fileparts(filePath);
if ~isempty(dirPath) && ~exist(dirPath, 'dir')
    mkdir(dirPath);
end

fid = fopen(filePath, 'w');
if fid == -1
    error('Failed to open output file: %s', filePath);
end

cleanup = onCleanup(@() fclose(fid));
fwrite(fid, content, 'char');
clear cleanup;
end

