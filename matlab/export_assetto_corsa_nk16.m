function content = buildDrivetrainIni(params, metrics)
gearRatios = resolveFieldOrDefault(params.powertrain, 'gear_ratios', [2.75 2.00 1.63 1.43 1.30 1.21]);
gearLines = cell(1, numel(gearRatios));
for i = 1:numel(gearRatios)
    gearLines{i} = sprintf('GEAR_%d=%.6f', i, gearRatios(i));
end

powerLock = clamp((90 - resolveFieldOrDefault(params.powertrain, 'lsd_ramp_accel', 35)) / 90, 0.05, 0.95);
coastLock = clamp((90 - resolveFieldOrDefault(params.powertrain, 'lsd_ramp_decel', 50)) / 90, 0.05, 0.95);
preload = max(resolveFieldOrDefault(params.powertrain, 'lsd_preload', 40), 0);

content = sprintf([ ...
    '[HEADER]\n' ...
    'VERSION=3\n\n' ...
    '[TRACTION]\n' ...
    'TYPE=RWD\n\n' ...
    '[GEARS]\n' ...
    'COUNT=%d\n' ...
    'GEAR_R=-3.000000\n' ...
    '%s\n' ...
    'FINAL=%.6f\n\n' ...
    '[DIFFERENTIAL]\n' ...
    'POWER=%.6f\n' ...
    'COAST=%.6f\n' ...
    'PRELOAD=%.6f\n\n' ...
    '[GEARBOX]\n' ...
    'CHANGE_UP_TIME=80\n' ...
    'CHANGE_DN_TIME=90\n' ...
    'AUTO_CUTOFF_TIME=75\n' ...
    'SUPPORTS_SHIFTER=0\n' ...
    'VALID_SHIFT_RPM_WINDOW=1200\n' ...
    'CONTROLS_WINDOW_GAIN=0.5\n' ...
    'INERTIA=0.020\n\n' ...
    '[CLUTCH]\n' ...
    'MAX_TORQUE=%.3f\n\n' ...
    '[AUTOCLUTCH]\n' ...
    'USE_ON_CHANGES=1\n' ...
    'MIN_RPM=%d\n' ...
    'MAX_RPM=%d\n'], ...
    numel(gearRatios), strjoin(gearLines, newline), ...
    resolveFieldOrDefault(params.powertrain, 'final_ratio', 4.0), ...
    powerLock, coastLock, preload, ...
    max(metrics.max_torque_nm * max(gearRatios) * resolveFieldOrDefault(params.powertrain, 'final_ratio', 4.0), 500), ...
    max(1200, round(min(resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [1000])))), ...
    max(3000, round(min(resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [1000])) + 2000)));
end

function content = buildEngineIni(params, metrics)
rpmPoints = resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [1000 3000 5000 7000 9000 11000 13000 14500]);
torqueCurve = resolveFieldOrDefault(params.powertrain, 'engine_torque_curve', [35 40 48 54 60 62 60 55]);
idleRpm = round(min(rpmPoints));
coastRpm = round(rpmPoints(min(numel(rpmPoints), max(1, ceil(numel(rpmPoints) * 0.5)))));
coastTorque = max(10, 0.20 * max(torqueCurve));

content = sprintf([ ...
    '[ENGINE_DATA]\n' ...
    'INERTIA=0.120\n' ...
    'LIMITER=%d\n' ...
    'MINIMUM=%d\n' ...
    'STALL_RPM=%d\n\n' ...
    '[COAST_REF]\n' ...
    'RPM=%d\n' ...
    'TORQUE=%.3f\n'], ...
    round(max(rpmPoints)), idleRpm, max(800, idleRpm - 200), coastRpm, coastTorque);
end

function content = buildPowerLut(params)
rpmPoints = resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [1000 3000 5000 7000 9000 11000 13000 14500]);
torqueCurve = resolveFieldOrDefault(params.powertrain, 'engine_torque_curve', [35 40 48 54 60 62 60 55]);
lines = cell(1, numel(rpmPoints) + 1);
lines{1} = sprintf('0\t|\t0');
for i = 1:numel(rpmPoints)
    lines{i+1} = sprintf('%g\t|\t%.6f', rpmPoints(i), torqueCurve(i));
end
content = strjoin(lines, newline);
content = [content newline];
end

