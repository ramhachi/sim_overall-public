function width = inferTireWidth(params)
modelText = '';
if isfield(params.tire, 'model_name') && ~isempty(params.tire.model_name)
    modelText = char(string(params.tire.model_name));
elseif isfield(params.tire, 'model') && ~isempty(params.tire.model)
    modelText = char(string(params.tire.model));
end

tokens = regexp(modelText, '(\d+(?:\.\d+)?)x(\d+(?:\.\d+)?)', 'tokens', 'once');
if ~isempty(tokens)
    widthInch = str2double(tokens{2});
    if isfinite(widthInch) && widthInch > 0
        width = widthInch * 0.0254;
        return;
    end
end

width = 0.180;
end

function topSpeedKmh = computeTopSpeedKmh(params, metrics)
gearRatios = resolveFieldOrDefault(params.powertrain, 'gear_ratios', [2.75 2.00 1.63 1.43 1.30 1.21]);
topGear = gearRatios(end);
primary = resolveFieldOrDefault(params.powertrain, 'primary_ratio', 1.90);
finalRatio = resolveFieldOrDefault(params.powertrain, 'final_ratio', 4.0);
wheelOmega = metrics.redline_rpm / 60 * 2 * pi / max(primary * finalRatio * topGear, eps);
topSpeedKmh = wheelOmega * metrics.tire_radius * 3.6;
end

function peakPowerKw = computePeakPowerKw(params)
rpm = resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [1000 3000 5000 7000 9000 11000 13000 14500]);
torque = resolveFieldOrDefault(params.powertrain, 'engine_torque_curve', [35 40 48 54 60 62 60 55]);
peakPowerKw = max(rpmToPowerKw(rpm, torque));
end

function maxBrakeTorque = computeMaxBrakeTorque(params)
pressure = resolveFieldOrDefault(params.brake, 'max_pressure', 8e6);
area = resolveFieldOrDefault(params.brake, 'caliper_area', [0.002 0.002 0.0015 0.0015]);
radius = resolveFieldOrDefault(params.brake, 'effective_radius', [0.10 0.10 0.09 0.09]);
muPad = resolveFieldOrDefault(params.brake, 'mu_pad', 0.45);
wheelTorque = pressure .* area .* radius .* muPad;
maxBrakeTorque = sum(wheelTorque);
end

