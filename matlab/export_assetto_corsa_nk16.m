function result = export_assetto_corsa_nk16(vehicleJsonPath, varargin)
% EXPORT_ASSETTO_CORSA_NK16 Export sim_overall vehicle params to an NK16-compatible AC overlay.

p = inputParser;
addParameter(p, 'OutputCarDir', '');
addParameter(p, 'TemplateCarDir', '');
addParameter(p, 'ScreenName', '');
parse(p, varargin{:});
opts = p.Results;

thisDir = fileparts(mfilename('fullpath'));
projectRoot = fileparts(thisDir);

if nargin < 1 || isempty(vehicleJsonPath)
    [vehicleJsonPath, candidate] = getDefaultVehicleJson(projectRoot);
else
    candidate = struct('label', toProjectRelativePath(char(vehicleJsonPath), projectRoot));
end

artifact = load_vehicle_artifact(vehicleJsonPath);
if ~isExportReadyArtifact(artifact, vehicleJsonPath)
    error(['Assetto Corsa export requires a complete vehicle JSON with mass/suspension/tire/powertrain/aero/brake sections. ' ...
        'Partial presets and aggregate optimization summaries are not export candidates: %s'], vehicleJsonPath);
end
params = merge_nested_structs(create_vehicle_baseline_template(), artifact.params);

if isempty(opts.OutputCarDir)
    outputCarDir = fullfile(projectRoot, 'output', 'assetto_corsa', 'NK16_ICV');
else
    outputCarDir = char(opts.OutputCarDir);
end
dataDir = fullfile(outputCarDir, 'data');
uiDir = fullfile(outputCarDir, 'ui');

if ~exist(outputCarDir, 'dir')
    mkdir(outputCarDir);
end

if ~isempty(opts.TemplateCarDir)
    copyTemplateCarFiles(char(opts.TemplateCarDir), outputCarDir);
end
if ~exist(dataDir, 'dir')
    mkdir(dataDir);
end
if ~exist(uiDir, 'dir')
    mkdir(uiDir);
end

metrics = deriveVehicleMetrics(params);

writeTextFile(fullfile(dataDir, 'car.ini'), buildCarIni(params, metrics));
writeTextFile(fullfile(dataDir, 'suspensions.ini'), buildSuspensionsIni(params, metrics));
writeTextFile(fullfile(dataDir, 'drivetrain.ini'), buildDrivetrainIni(params, metrics));
writeTextFile(fullfile(dataDir, 'engine.ini'), buildEngineIni(params, metrics));
writeTextFile(fullfile(dataDir, 'power.lut'), buildPowerLut(params));
writeTextFile(fullfile(dataDir, 'brakes.ini'), buildBrakesIni(params, metrics));
writeTextFile(fullfile(dataDir, 'tyres.ini'), buildTyresIni(params, metrics));
writeTextFile(fullfile(dataDir, 'tire_front_lat_curve.lut'), buildLatCurveLut(metrics.mu_y_front));
writeTextFile(fullfile(dataDir, 'tire_front_long_curve.lut'), buildLongCurveLut(metrics.mu_x_front));
writeTextFile(fullfile(dataDir, 'tire_rear_lat_curve.lut'), buildLatCurveLut(metrics.mu_y_rear));
writeTextFile(fullfile(dataDir, 'tire_rear_long_curve.lut'), buildLongCurveLut(metrics.mu_x_rear));
writeTextFile(fullfile(dataDir, 'aero.ini'), buildAeroIni(params, metrics));
writeTextFile(fullfile(dataDir, 'front_wing_AOA_CL.lut'), buildWingAoAClLut());
writeTextFile(fullfile(dataDir, 'front_wing_AOA_CD.lut'), buildWingAoACdLut());
writeTextFile(fullfile(dataDir, 'rear_wing_AOA_CL.lut'), buildWingAoAClLut());
writeTextFile(fullfile(dataDir, 'rear_wing_AOA_CD.lut'), buildWingAoACdLut());
writeTextFile(fullfile(dataDir, 'README_sim_overall_export.txt'), buildOverlayReadme(vehicleJsonPath, outputCarDir));

screenName = opts.ScreenName;
if isempty(screenName)
    [~, fileBase] = fileparts(vehicleJsonPath);
    screenName = sprintf('Formula TMU Export (%s)', fileBase);
end
writePrettyJson(fullfile(uiDir, 'ui_car.json'), buildUiCarJson(params, metrics, screenName));

metadata = struct( ...
    'generated_at', datestr(now, 'yyyy-mm-dd HH:MM:SS'), ...
    'source_vehicle_json', vehicleJsonPath, ...
    'source_vehicle_label', candidate.label, ...
    'output_car_dir', outputCarDir, ...
    'generated_files', {{ ...
        'data/car.ini', ...
        'data/suspensions.ini', ...
        'data/drivetrain.ini', ...
        'data/engine.ini', ...
        'data/power.lut', ...
        'data/brakes.ini', ...
        'data/tyres.ini', ...
        'data/tire_front_lat_curve.lut', ...
        'data/tire_front_long_curve.lut', ...
        'data/tire_rear_lat_curve.lut', ...
        'data/tire_rear_long_curve.lut', ...
        'data/aero.ini', ...
        'data/front_wing_AOA_CL.lut', ...
        'data/front_wing_AOA_CD.lut', ...
        'data/rear_wing_AOA_CL.lut', ...
        'data/rear_wing_AOA_CD.lut', ...
        'ui/ui_car.json' ...
    }}, ...
    'notes', {{ ...
        'This export prepares a swappable NK16_ICV overlay package.', ...
        'Copy the generated data/ and ui/ into an extracted NK16_ICV car folder to replace its internal parameters.' ...
    }});
writePrettyJson(fullfile(outputCarDir, 'sim_overall_export_metadata.json'), metadata);

result = struct();
result.output_car_dir = outputCarDir;
result.data_dir = dataDir;
result.ui_dir = uiDir;
result.source_vehicle_json = vehicleJsonPath;
result.screen_name = screenName;
end

function [vehicleJsonPath, candidate] = getDefaultVehicleJson(projectRoot)
candidates = find_vehicle_json_candidates(projectRoot, 'RequireExportReady', true);
if isempty(candidates)
    error('No vehicle JSON candidates were found.');
end

optimizedIdx = find([candidates.is_optimized]);
if isempty(optimizedIdx)
    candidate = candidates(1);
else
    [~, newestIdxWithinOptimized] = max([candidates(optimizedIdx).datenum]);
    candidate = candidates(optimizedIdx(newestIdxWithinOptimized));
end
vehicleJsonPath = candidate.path;
end

function tf = isExportReadyArtifact(artifact, ~)
rawParams = artifact.params;
tf = isstruct(rawParams) && isfield(rawParams, 'mass') && isfield(rawParams, 'suspension') ...
    && isfield(rawParams, 'tire') && isfield(rawParams, 'powertrain') ...
    && isfield(rawParams, 'aero') && isfield(rawParams, 'brake');
end

function metrics = deriveVehicleMetrics(params)
metrics = struct();
metrics.mass_total = params.mass.m_total;
metrics.wheelbase = params.mass.wheelbase;
metrics.a = resolveFieldOrDefault(params.mass, 'a', params.mass.wheelbase * 0.5);
metrics.b = resolveFieldOrDefault(params.mass, 'b', params.mass.wheelbase - metrics.a);
metrics.front_weight_fraction = clamp(metrics.b / max(metrics.wheelbase, eps), 0.30, 0.70);
metrics.cg_height = resolveFieldOrDefault(params.mass, 'h_cg', 0.28);
metrics.track_front = resolveFieldOrDefault(params.mass, 'track_f', 1.20);
metrics.track_rear = resolveFieldOrDefault(params.mass, 'track_r', 1.18);
metrics.tire_radius = resolveFieldOrDefault(params.tire, 'radius', 0.228);
metrics.tire_width = inferTireWidth(params);
metrics.unsprung = resolveFieldOrDefault(params.mass, 'm_unsprung', [12 12 14 14]);
metrics.front_hub_mass = mean(metrics.unsprung(1:2));
metrics.rear_hub_mass = mean(metrics.unsprung(3:4));
metrics.motion_ratio = resolveFieldOrDefault(params.suspension, 'motion_ratio', [0.85 0.85 0.90 0.90]);
metrics.spring_rate = resolveFieldOrDefault(params.suspension, 'k_spring', [30000 30000 25000 25000]);
metrics.wheel_rate = metrics.spring_rate .* (metrics.motion_ratio .^ 2);
baseDamper = resolveFieldOrDefault(params.suspension, 'c0', 1500.0);
if isscalar(baseDamper)
    metrics.damper_rate = [baseDamper baseDamper baseDamper baseDamper] .* (metrics.motion_ratio .^ 2);
else
    metrics.damper_rate = reshape(baseDamper, 1, []) .* (metrics.motion_ratio .^ 2);
end
metrics.static_camber_deg = rad2degVector(resolveFieldOrDefault(params.suspension, 'static_camber', [-0.03 -0.03 -0.02 -0.02]));
metrics.static_toe = resolveFieldOrDefault(params.suspension, 'static_toe', [0 0 0 0]);
metrics.mu_x_front = resolveFieldOrDefault(params.tire, 'mu_x_max', 1.6);
metrics.mu_x_rear = metrics.mu_x_front;
metrics.mu_y_front = resolveFieldOrDefault(params.tire, 'mu_y_max', 2.0);
metrics.mu_y_rear = metrics.mu_y_front;
metrics.inertia_radius = [ ...
    sqrt(max(resolveFieldOrDefault(params.mass, 'Ixx', 32.0), 1e-6) / max(metrics.mass_total, 1e-6)), ...
    sqrt(max(resolveFieldOrDefault(params.mass, 'Iyy', 95.0), 1e-6) / max(metrics.mass_total, 1e-6)), ...
    sqrt(max(resolveFieldOrDefault(params.mass, 'Izz', 85.0), 1e-6) / max(metrics.mass_total, 1e-6))];
metrics.max_power_kw = computePeakPowerKw(params);
metrics.max_torque_nm = max(resolveFieldOrDefault(params.powertrain, 'engine_torque_curve', [55]));
metrics.redline_rpm = max(resolveFieldOrDefault(params.powertrain, 'engine_rpm_points', [14500]));
metrics.top_speed_kmh = computeTopSpeedKmh(params, metrics);
metrics.brake_front_share = clamp(resolveFieldOrDefault(params.brake, 'balance', 0.55), 0.40, 0.70);
metrics.max_brake_torque = computeMaxBrakeTorque(params);
metrics.aero_balance = clamp(resolveFieldOrDefault(params.aero, 'aero_balance', 0.50), 0.20, 0.80);
metrics.cla = max(resolveFieldOrDefault(params.aero, 'CL_A', 0.0), 0.0);
metrics.cda = max(resolveFieldOrDefault(params.aero, 'CD_A', 0.0), 0.0);
metrics.driver_eyes_y = max(metrics.tire_radius + 0.95 * metrics.cg_height, 0.55);
metrics.driver_eyes_z = -0.35;
metrics.graphics_offset_y = -metrics.cg_height;
metrics.steer_ratio = clamp(1.0 / max(resolveFieldOrDefault(params.steering, 'rack_ratio', 0.18), 0.08), 4.0, 12.0);
metrics.ffmult = clamp(resolveFieldOrDefault(params.steering, 'C_steer_torque', 0.5), 0.2, 1.5);
metrics.linear_steer_rod_ratio = clamp(0.001 + 0.001 * (resolveFieldOrDefault(params.steering, 'ackermann', 0.7) - 0.5), 0.0005, 0.0030);
end

