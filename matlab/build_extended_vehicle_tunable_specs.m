function specs = build_extended_vehicle_tunable_specs()
% BUILD_EXTENDED_VEHICLE_TUNABLE_SPECS
% Extra shared vehicle parameters that were previously hardcoded or only
% available through implicit defaults.

specs = [ ...
    make_spec('BrakeBalance', 0.45, 0.70, 'field', {'brake', 'balance'}, 'Front brake balance fraction', '-'), ...
    make_spec('SteeringAckermann', 0.0, 1.0, 'field', {'steering', 'ackermann'}, 'Ackermann ratio', '-'), ...
    make_spec('EngineTorqueScale', 0.85, 1.15, 'engine_torque_scale', {}, 'Torque-curve scale factor', '-'), ...
    make_spec('TireFzNom', 900.0, 2200.0, 'field', {'tire', 'Fz_nom'}, 'Nominal tire load', 'N'), ...
    make_spec('TireRelaxationLx', 0.05, 0.35, 'field', {'tire', 'relaxation', 'Lx_base'}, 'Longitudinal relaxation length', 'm'), ...
    make_spec('TireRelaxationLy', 0.08, 0.60, 'field', {'tire', 'relaxation', 'Ly_base'}, 'Lateral relaxation length', 'm'), ...
    make_spec('TireCx', 50000.0, 140000.0, 'field', {'tire', 'Cx'}, 'TMeasy longitudinal stiffness proxy', 'N/m'), ...
    make_spec('TireCy', 12000.0, 50000.0, 'field', {'tire', 'Cy'}, 'TMeasy lateral stiffness proxy', 'N/rad'), ...
    make_spec('TireVerticalK', 100000.0, 350000.0, 'field', {'tire', 'k_tire'}, 'Vertical tire stiffness', 'N/m'), ...
    make_spec('TireVerticalC', 100.0, 2500.0, 'field', {'tire', 'c_tire'}, 'Vertical tire damping', 'Ns/m'), ...
    make_spec('BumpStopGap', 0.01, 0.08, 'field', {'suspension', 'bump_stop_gap'}, 'Bump-stop engagement gap', 'm'), ...
    make_spec('BumpStopK', 20000.0, 350000.0, 'field', {'suspension', 'bump_stop_k'}, 'Bump-stop stiffness', 'N/m'), ...
    make_spec('ChassisStiffness', 1000.0, 3500.0, 'field', {'suspension', 'K_chassis'}, 'Frame torsional stiffness', 'Nm/deg'), ...
    make_spec('ChassisDamping', 1.0, 20.0, 'field', {'suspension', 'C_chassis'}, 'Frame torsional damping', 'Nm*s/rad'), ...
    make_spec('ChassisTwistInertia', 0.5, 4.0, 'field', {'suspension', 'I_twist'}, 'Frame torsional inertia', 'kg*m^2') ...
];

% Suspension hardpoint offsets from the profile's reference geometry, per axle
% (left corner; the right corner gets the Y-mirror). compute_vehicle_kc applies
% them and re-solves the K&C for every candidate. Up/Out are positive upward
% and away from the car centreline.
hardpoints = { ...
    'UpperInnerUp', 'upper_inner_up', 0.05, 'Upper-arm chassis pickups height'; ...
    'UpperInnerOut', 'upper_inner_out', 0.05, 'Upper-arm chassis pickups lateral'; ...
    'LowerInnerUp', 'lower_inner_up', 0.05, 'Lower-arm chassis pickups height'; ...
    'LowerInnerOut', 'lower_inner_out', 0.05, 'Lower-arm chassis pickups lateral'; ...
    'UBJUp', 'ubj_up', 0.03, 'Upper ball joint height'; ...
    'LBJUp', 'lbj_up', 0.03, 'Lower ball joint height'; ...
    'TieRodUp', 'tie_rod_up', 0.03, 'Tie rod / toe link height (both ends)'};
axles = {'F', 'front'; 'R', 'rear'};
for a = 1:2
    for h = 1:size(hardpoints, 1)
        specs(end + 1) = make_spec(['HP_', hardpoints{h, 1}, '_', axles{a, 1}], ... %#ok<AGROW>
            -hardpoints{h, 3}, hardpoints{h, 3}, 'field', ...
            {'suspension', 'hardpoint_offsets', axles{a, 2}, hardpoints{h, 2}}, ...
            [hardpoints{h, 4}, ' offset (', axles{a, 2}, ')'], 'm');
    end
end
end

function spec = make_spec(name, lower, upper, apply_mode, path, description, unit)
spec = struct( ...
    'name', name, ...
    'lower', lower, ...
    'upper', upper, ...
    'apply_mode', apply_mode, ...
    'path', {path}, ...
    'description', description, ...
    'unit', unit, ...
    'index', []);
end
