function trainAceDriverPhase4Extension(varargin)
% TRAINACEDRIVERPHASE4EXTENSION Continue a completed ace run with extra phase-4 polishing.
%
% Starts from the current ace final agent, writes into a new run directory,
% and focuses on mixed-track phase-4 continuation to recover completion
% margin while retaining autocross speed.

ensure_rl_driver_paths();

p = inputParser;
addParameter(p, 'ResumeAgentPath', fullfile('rl_results', 'curriculum_torque_frame_fresh_v1', ...
    'phase34_ace_driver_from_phase3_final', 'final_agent.mat'));
addParameter(p, 'SaveBaseDir', fullfile('rl_results', 'curriculum_torque_frame_fresh_v1', ...
    'phase4_ace_extension_from_ace_final'));
addParameter(p, 'CompletedEpisodesOffset', []);
addParameter(p, 'Phase4Episodes', 2160);
addParameter(p, 'Phase4Steps', 6500);
addParameter(p, 'RandInterval', 100);
addParameter(p, 'RandStrength', 0.20);
addParameter(p, 'SaveAgentValue', 20);
addParameter(p, 'ScoreAveragingWindowLength', 50);
addParameter(p, 'Plots', 'training-progress');
addParameter(p, 'Verbose', true);
parse(p, varargin{:});
opts = p.Results;

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
resumeAgentPath = resolveProjectRelativePath(opts.ResumeAgentPath, projectRoot);
saveBaseDir = resolveProjectRelativePath(opts.SaveBaseDir, projectRoot);

completedEpisodesOffset = opts.CompletedEpisodesOffset;
if isempty(completedEpisodesOffset)
    completedEpisodesOffset = inferSourceCompletedEpisodesOffset(resumeAgentPath);
end

continuationState = resolvePhase34RecoveryState( ...
    'ResumeAgentPath', resumeAgentPath, ...
    'SaveBaseDir', saveBaseDir, ...
    'PhaseEpisodes', [1, 1, 1, opts.Phase4Episodes], ...
    'CompletedEpisodesOffset', completedEpisodesOffset, ...
    'DefaultStartPhase', 4, ...
    'InitialMode', 'fresh_phase4_extension', ...
    'InitialMessage', 'Starting a fresh phase-4 ace extension run from the completed ace final agent.');
[resumeAgent, resumeVarName] = loadRLAgentFromFile(continuationState.resume_agent_path); %#ok<ASGLU>

envOverrides = struct( ...
    'CrawlWindowSteps', 100, ...
    'CrawlMinProgress', 5.0, ...
    'W_lowSpeedBrake', 14.0, ...
    'LowSpeedBrakeThreshold', 3.0, ...
    'W_previewSteer', 20.0, ...
    'PreviewSteerSpeedThreshold', 14.0, ...
    'PreviewCurvatureThreshold', 0.010, ...
    'RollingStartSpeed', 6.0, ...
    'RollingStartThrottle', 0.45, ...
    'RollingStartMaxSteps', 60, ...
    'RollingStartHoldEpisodes', 240, ...
    'RollingStartFadeEpisodes', 480);

phaseTrackPools = {
    []
    []
    []
    {'autocross', 'autocross', 'autocross', 'autocross', 'autocross', 'autocross', ...
        'skidpad', 'skidpad', 'figure_eight', 'circle_R20', 'circle_cw_R20', ...
        'straight_corner'}
    };

phaseRewardOverrides = {
    []
    []
    []
    struct('W_speed', 1.00, 'W_boundary', 44.0, 'W_centering', 2.8, ...
        'W_heading', 2.5, 'W_alive', 0.05, 'W_lap', 280.0, 'W_jerk', 0.04)
    };

fprintf('=== Ace-driver phase-4 extension training ===\n');
fprintf('Continuation mode: %s\n', continuationState.mode);
fprintf('%s\n', continuationState.message);
fprintf('Resume agent: %s\n', continuationState.resume_agent_path);
fprintf('Save dir: %s\n', saveBaseDir);
fprintf('Completed episode offset: %d\n', continuationState.completed_episodes_offset);
fprintf('Phase episodes: %s\n', mat2str(continuationState.phase_episodes));
fprintf('Phase steps: %s\n', mat2str([500, 1500, 4500, opts.Phase4Steps]));

if strcmp(continuationState.mode, 'resume_partial_phase')
    writePhaseResumeState( ...
        continuationState.phase_resume_state_path, ...
        continuationState.current_phase_completed_episodes, ...
        continuationState.resume_agent_path);
end

startRLServer(projectRoot);
trainWithCurriculum('autocross', ...
    'ResumeAgent', resumeAgent, ...
    'SaveBaseDir', saveBaseDir, ...
    'PhaseEpisodes', continuationState.phase_episodes, ...
    'PhaseSteps', [500, 1500, 4500, opts.Phase4Steps], ...
    'EnvOverrides', envOverrides, ...
    'PhaseTrackPools', phaseTrackPools, ...
    'PhaseRewardOverrides', phaseRewardOverrides, ...
    'StartPhase', continuationState.start_phase, ...
    'CompletedEpisodesOffset', continuationState.completed_episodes_offset, ...
    'DomainRand', true, ...
    'RandInterval', opts.RandInterval, ...
    'RandStrength', opts.RandStrength, ...
    'SaveAgentCriteria', 'EpisodeCount', ...
    'SaveAgentValue', opts.SaveAgentValue, ...
    'ScoreAveragingWindowLength', opts.ScoreAveragingWindowLength, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 1e9, ...
    'Plots', opts.Plots, ...
    'Verbose', opts.Verbose);
end

function resolvedPath = resolveProjectRelativePath(pathValue, projectRoot)
pathStr = char(pathValue);
if startsWith(pathStr, filesep) || ~isempty(regexp(pathStr, '^[A-Za-z]:[\\/]', 'once'))
    resolvedPath = pathStr;
else
    resolvedPath = fullfile(projectRoot, pathStr);
end
end

function completedEpisodes = inferSourceCompletedEpisodesOffset(agentPath)
completedEpisodes = 0;
if ~(ischar(agentPath) || isstring(agentPath))
    return;
end

agentPath = char(agentPath);
runDir = fileparts(agentPath);
progressPath = fullfile(runDir, 'progress.json');
if ~isfile(progressPath)
    return;
end

progress = jsondecode(fileread(progressPath));
if isfield(progress, 'completed_episodes') && isnumeric(progress.completed_episodes) ...
        && isscalar(progress.completed_episodes) && isfinite(progress.completed_episodes)
    completedEpisodes = double(progress.completed_episodes);
end
end

function writePhaseResumeState(statePath, phaseEpisodeOffset, resumeSourceCheckpoint)
stateDir = fileparts(statePath);
if ~isempty(stateDir) && ~exist(stateDir, 'dir')
    mkdir(stateDir);
end

fid = fopen(statePath, 'w');
if fid == -1
    error('Failed to write phase resume state: %s', statePath);
end

cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(struct( ...
    'phase_episode_offset', phaseEpisodeOffset, ...
    'resume_source_checkpoint', resumeSourceCheckpoint, ...
    'session_started_datenum', now, ...
    'updated_at', datestr(now, 'yyyy-mm-dd HH:MM:SS'))));
clear cleanup;
end
