% trainCurriculumV7.m — カリキュラム学習: 段階的に難しいトラック
% Phase 1: 大半径の円 (R=30, 20) CW/CCW
% Phase 2: 小半径の円 (R=15, 10, 7) + straight_corner + skidpad
% Phase 3: オートクロス + 復習
% 使い方: cd matlab/rl_driver && trainCurriculumV7

%% Phase 1: 基本操作（大半径円、CW/CCW）
fprintf('=== Phase 1: Basic circles (R=30, R=20, CW+CCW) ===\n');
env = FSAEEnvironment('circle');
env.TrackPool = {'circle', 'circle_cw', 'circle_R20', 'circle_cw_R20'};
agent = createSACAgent(env);

outDir1 = fullfile(pwd, '../../rl_results/curriculum_v7_p1');
if ~exist(outDir1, 'dir'), mkdir(outDir1); end

trainOpts1 = rlTrainingOptions( ...
    'MaxEpisodes', 200, ...
    'MaxStepsPerEpisode', env.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 20, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 600, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 100, ...
    'SaveAgentDirectory', outDir1);

stats1 = train(agent, env, trainOpts1);
save(fullfile(outDir1, 'trained_agent.mat'), 'agent');
fprintf('Phase 1: %d eps, max=%.0f\n', length(stats1.EpisodeReward), max(stats1.EpisodeReward));
delete(env);

%% Phase 2: 多様なコーナリング（タイト＋S字＋スキッドパッド）
fprintf('=== Phase 2: Tight corners (R=15,10,7 + skidpad + straight_corner) ===\n');
env2 = FSAEEnvironment('circle');
env2.TrackPool = {'circle', 'circle_cw', ...
    'circle_R20', 'circle_cw_R20', ...
    'circle_R15', 'circle_cw_R15', ...
    'circle_R10', 'circle_cw_R10', ...
    'circle_R7', 'circle_cw_R7', ...
    'skidpad', 'straight_corner'};

outDir2 = fullfile(pwd, '../../rl_results/curriculum_v7_p2');
if ~exist(outDir2, 'dir'), mkdir(outDir2); end

trainOpts2 = rlTrainingOptions( ...
    'MaxEpisodes', 300, ...
    'MaxStepsPerEpisode', env2.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 30, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 400, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 50, ...
    'SaveAgentDirectory', outDir2);

stats2 = train(agent, env2, trainOpts2);
save(fullfile(outDir2, 'trained_agent.mat'), 'agent');
fprintf('Phase 2: %d eps, max=%.0f\n', length(stats2.EpisodeReward), max(stats2.EpisodeReward));
delete(env2);

%% Phase 3: オートクロス中心 + 復習
fprintf('=== Phase 3: Autocross + review ===\n');
env3 = FSAEEnvironment('circle');
env3.TrackPool = {'autocross', 'autocross', 'autocross', 'autocross', ...
    'circle', 'circle_cw', 'skidpad', ...
    'circle_R10', 'circle_cw_R10', 'straight_corner'};
env3.MaxEpisodeSteps = 8000;  % 160秒

outDir3 = fullfile(pwd, '../../rl_results/curriculum_v7_final');
if ~exist(outDir3, 'dir'), mkdir(outDir3); end

trainOpts3 = rlTrainingOptions( ...
    'MaxEpisodes', 500, ...
    'MaxStepsPerEpisode', env3.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 30, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 600, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 50, ...
    'SaveAgentDirectory', outDir3);

stats3 = train(agent, env3, trainOpts3);
save(fullfile(outDir3, 'trained_agent.mat'), 'agent');
save(fullfile(outDir3, 'training_stats.mat'), 'stats3');
fprintf('Phase 3: %d eps, max=%.0f\n', length(stats3.EpisodeReward), max(stats3.EpisodeReward));

%% エクスポート
exportActorForCpp(agent, fullfile(pwd, 'rl_actor_export'));
exportActorForCpp(agent, outDir3);
fprintf('Export complete.\n');

delete(env3);
fprintf('All done.\n');
