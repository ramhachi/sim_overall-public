% trainMultiTrackV5.m — 多様なトラックでの学習（circle CW/CCW + skidpad + autocross）
% 使い方: cd matlab/rl_driver && trainMultiTrackV5

%% Phase 1: 円形コース学習（両方向）
fprintf('=== Phase 1: Bidirectional circle pre-training ===\n');
env = FSAEEnvironment('circle');
env.TrackPool = {'circle', 'circle_cw'};
agent = createSACAgent(env);
fprintf('Agent created (2D action)\n');

outDir1 = fullfile(pwd, '../../rl_results/multi_v5_phase1');
if ~exist(outDir1, 'dir'), mkdir(outDir1); end

trainOpts1 = rlTrainingOptions( ...
    'MaxEpisodes', 200, ...
    'MaxStepsPerEpisode', env.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 20, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 600, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 100, ...
    'SaveAgentDirectory', outDir1);

stats1 = train(agent, env, trainOpts1);
save(fullfile(outDir1, 'trained_agent.mat'), 'agent');
save(fullfile(outDir1, 'training_stats.mat'), 'stats1');
fprintf('Phase 1 done. Episodes: %d, Max reward: %.0f\n', ...
    length(stats1.EpisodeReward), max(stats1.EpisodeReward));
delete(env);

%% Phase 2: スキッドパッド学習（既存の重みから継続）
fprintf('=== Phase 2: Skidpad fine-tuning ===\n');
env2 = FSAEEnvironment('circle');
env2.TrackPool = {'circle', 'circle_cw', 'skidpad'};

outDir2 = fullfile(pwd, '../../rl_results/multi_v5_phase2');
if ~exist(outDir2, 'dir'), mkdir(outDir2); end

trainOpts2 = rlTrainingOptions( ...
    'MaxEpisodes', 200, ...
    'MaxStepsPerEpisode', env2.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 20, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 500, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 50, ...
    'SaveAgentDirectory', outDir2);

stats2 = train(agent, env2, trainOpts2);
save(fullfile(outDir2, 'trained_agent.mat'), 'agent');
save(fullfile(outDir2, 'training_stats.mat'), 'stats2');
fprintf('Phase 2 done. Episodes: %d, Max reward: %.0f\n', ...
    length(stats2.EpisodeReward), max(stats2.EpisodeReward));
delete(env2);

%% Phase 3: オートクロス学習
fprintf('=== Phase 3: Autocross fine-tuning ===\n');
env3 = FSAEEnvironment('circle');
env3.TrackPool = {'circle', 'circle_cw', 'skidpad', 'autocross'};
env3.MaxEpisodeSteps = 10000;  % 200秒（autocross用に延長）

outDir3 = fullfile(pwd, '../../rl_results/multi_v5_final');
if ~exist(outDir3, 'dir'), mkdir(outDir3); end

trainOpts3 = rlTrainingOptions( ...
    'MaxEpisodes', 300, ...
    'MaxStepsPerEpisode', env3.MaxEpisodeSteps, ...
    'ScoreAveragingWindowLength', 30, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 400, ...
    'SaveAgentCriteria', 'EpisodeReward', ...
    'SaveAgentValue', 50, ...
    'SaveAgentDirectory', outDir3);

stats3 = train(agent, env3, trainOpts3);
save(fullfile(outDir3, 'trained_agent.mat'), 'agent');
save(fullfile(outDir3, 'training_stats.mat'), 'stats3');
fprintf('Phase 3 done. Episodes: %d, Max reward: %.0f\n', ...
    length(stats3.EpisodeReward), max(stats3.EpisodeReward));

%% C++エクスポート
exportActorForCpp(agent, fullfile(pwd, 'rl_actor_export'));
exportActorForCpp(agent, outDir3);
fprintf('Export complete.\n');

delete(env3);
fprintf('All done.\n');
