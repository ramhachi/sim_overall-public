function trainPhase34Recovery(varargin)
% TRAINPHASE34RECOVERY Resume later-phase curriculum from the strongest stable phase-3 agent.
%
% This helper is intended for long mixed-track continuation runs after a
% phase-4 forgetting event. It resumes from the latest stable phase-3
% checkpoint, keeps the always-on preview-steer shaping that recovered
% circle, and mixes review tracks into phase 4 so circle/skidpad skill is
% not forgotten while autocross is learned.

ensure_rl_driver_paths();

p = inputParser;
addParameter(p, 'ResumeAgentPath', fullfile('rl_results', 'curriculum_torque_frame_fresh_v1', ...
    'phase3_phase4_from_phase2o', 'phase3_skidpad', 'agent.mat'));
addParameter(p, 'SaveBaseDir', fullfile('rl_results', 'curriculum_torque_frame_fresh_v1', ...
    'phase34_recovery_from_phase3_final'));
addParameter(p, 'CompletedEpisodesOffset', []);
addParameter(p, 'PhaseEpisodes', [1, 1, 240, 480]);
addParameter(p, 'PhaseSteps', [500, 1500, 3000, 6000]);
addParameter(p, 'RandInterval', 100);
addParameter(p, 'RandStrength', 0.3);
addParameter(p, 'SaveAgentValue', 20);
addParameter(p, 'ScoreAveragingWindowLength', 20);
addParameter(p, 'Plots', 'training-progress');
addParameter(p, 'Verbose', true);
parse(p, varargin{:});
opts = p.Results;

if numel(opts.PhaseEpisodes) ~= 4 || numel(opts.PhaseSteps) ~= 4
    error('PhaseEpisodes and PhaseSteps must each contain 4 entries.');
end

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
resumeAgentPath = resolveProjectRelativePath(opts.ResumeAgentPath, projectRoot);
saveBaseDir = resolveProjectRelativePath(opts.SaveBaseDir, projectRoot);
recoveryState = resolvePhase34RecoveryState( ...
    'ResumeAgentPath', resumeAgentPath, ...
    'SaveBaseDir', saveBaseDir, ...
    'PhaseEpisodes', opts.PhaseEpisodes, ...
    'CompletedEpisodesOffset', opts.CompletedEpisodesOffset);
[resumeAgent, resumeVarName] = loadRLAgentFromFile(recoveryState.resume_agent_path); %#ok<ASGLU>

envOverrides = struct( ...
    'CrawlWindowSteps', 100, ...
    'CrawlMinProgress', 3.0, ...
    'W_lowSpeedBrake', 12.0, ...
    'LowSpeedBrakeThreshold', 2.0, ...
    'W_previewSteer', 25.0, ...
    'PreviewSteerSpeedThreshold', 0.0, ...
    'PreviewCurvatureThreshold', 0.01);

phaseTrackPools = {
    []
    []
    {'skidpad', 'skidpad', 'skidpad', 'figure_eight', 'figure_eight', ...
        'circle', 'circle_cw', 'circle_R20', 'circle_cw_R20'}
    {'autocross', 'autocross', 'autocross', 'autocross', 'autocross', ...
        'skidpad', 'skidpad', 'figure_eight', ...
        'circle', 'circle_cw', 'circle_R20', 'circle_cw_R20', 'straight_corner'}
    };

phaseRewardOverrides = {
    []
    []
    struct('W_boundary', 40, 'W_centering', 3.0, 'W_heading', 2.5)
    struct('W_boundary', 45, 'W_centering', 3.5, 'W_heading', 3.0, 'W_alive', 0.1)
    };

fprintf('=== Phase 3/4 recovery training ===\n');
fprintf('Recovery mode: %s\n', recoveryState.mode);
fprintf('%s\n', recoveryState.message);
fprintf('Resume agent: %s\n', recoveryState.resume_agent_path);
fprintf('Save dir: %s\n', saveBaseDir);
fprintf('Completed episode offset: %d\n', recoveryState.completed_episodes_offset);
fprintf('Phase episodes: %s\n', mat2str(recoveryState.phase_episodes));
fprintf('Phase steps: %s\n', mat2str(opts.PhaseSteps));

if strcmp(recoveryState.mode, 'resume_partial_phase')
    writePhaseResumeState( ...
        recoveryState.phase_resume_state_path, ...
        recoveryState.current_phase_completed_episodes, ...
        recoveryState.resume_agent_path);
end

startRLServer(projectRoot);
trainWithCurriculum('autocross', ...
    'ResumeAgent', resumeAgent, ...
    'SaveBaseDir', saveBaseDir, ...
    'PhaseEpisodes', recoveryState.phase_episodes, ...
    'PhaseSteps', opts.PhaseSteps, ...
    'EnvOverrides', envOverrides, ...
    'PhaseTrackPools', phaseTrackPools, ...
    'PhaseRewardOverrides', phaseRewardOverrides, ...
    'StartPhase', recoveryState.start_phase, ...
    'CompletedEpisodesOffset', recoveryState.completed_episodes_offset, ...
    'DomainRand', true, ...
    'RandInterval', opts.RandInterval, ...
    'RandStrength', opts.RandStrength, ...
    'SaveAgentCriteria', 'EpisodeCount', ...
    'SaveAgentValue', opts.SaveAgentValue, ...
    'ScoreAveragingWindowLength', opts.ScoreAveragingWindowLength, ...
    'StopTrainingCriteria', 'AverageReward', ...
    'StopTrainingValue', 1e9, ...
    'Plots', opts.Plots, ...
    'Verbose', opts.Verbose);
end

function resolvedPath = resolveProjectRelativePath(pathValue, projectRoot)
pathStr = char(pathValue);
if startsWith(pathStr, filesep) || ~isempty(regexp(pathStr, '^[A-Za-z]:[\\/]', 'once'))
    resolvedPath = pathStr;
else
    resolvedPath = fullfile(projectRoot, pathStr);
end
end

function writePhaseResumeState(statePath, phaseEpisodeOffset, resumeSourceCheckpoint)
stateDir = fileparts(statePath);
if ~isempty(stateDir) && ~exist(stateDir, 'dir')
    mkdir(stateDir);
end

fid = fopen(statePath, 'w');
if fid == -1
    error('Failed to write phase resume state: %s', statePath);
end

cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(struct( ...
    'phase_episode_offset', phaseEpisodeOffset, ...
    'resume_source_checkpoint', resumeSourceCheckpoint, ...
    'session_started_datenum', now, ...
    'updated_at', datestr(now, 'yyyy-mm-dd HH:MM:SS'))));
clear cleanup;
end
