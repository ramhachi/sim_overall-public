function resumeAceDriverPhase4ExtensionAfterRestart()
% RESUMEACEDRIVERPHASE4EXTENSIONAFTERRESTART
% 1) keep the current deployment candidate if one already exists
% 2) otherwise publish the current safest fallback deployment candidate
% 3) resume or start the ace phase-4 extension run

projectRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
deploymentAgentPath = fullfile(projectRoot, 'rl_results', 'deployment', 'deployment_agent.mat');
fallbackAgentPath = fullfile(projectRoot, 'rl_results', ...
    'curriculum_torque_frame_fresh_v1', ...
    'phase34_recovery_from_phase3_final', ...
    'final_agent.mat');
sourceAgentPath = fullfile(projectRoot, 'rl_results', ...
    'curriculum_torque_frame_fresh_v1', ...
    'phase34_ace_driver_from_phase3_final', ...
    'final_agent.mat');

fprintf('=== Ace-driver phase-4 extension bootstrap ===\n');
if ~isfile(sourceAgentPath)
    error('Completed ace final agent not found: %s', sourceAgentPath);
end

if isfile(deploymentAgentPath)
    fprintf('Keeping existing deployment candidate: %s\n', deploymentAgentPath);
elseif isfile(fallbackAgentPath)
    fprintf('Publishing fallback deployment candidate: %s\n', fallbackAgentPath);
    publishRLDeploymentCandidate(fallbackAgentPath, ...
        'Metadata', struct( ...
            'published_reason', 'safe_fallback_before_ace_phase4_extension', ...
            'published_by', mfilename));
end

fprintf('Starting ace phase-4 extension run...\n');
trainAceDriverPhase4Extension( ...
    'ResumeAgentPath', sourceAgentPath, ...
    'Phase4Episodes', 2160, ...
    'ScoreAveragingWindowLength', 50, ...
    'SaveAgentValue', 20, ...
    'Plots', 'none');
end
