function result = run_full_vehicle_ga(config)
% RUN_FULL_VEHICLE_GA Run the resumable high-fidelity LPV full-vehicle GA.

defaults = vehicle_ga_default_config();
if nargin < 1 || isempty(config)
    config = defaults;
else
    config = merge_nested_structs(defaults, config);
end
config = validate_config(config);

schema = build_full_vehicle_design_schema();
active_schema = vehicle_ga_active_schema(schema);

base_params = create_vehicle_baseline_template();
torque_preset_path = fullfile(config.project_root, 'matlab', ...
    'parameter_presets', 'params_flexible_torque.json');
base_params = merge_nested_structs(base_params, jsondecode(fileread(torque_preset_path)));
[base_params, selected_tire] = apply_named_tire_model_selection( ...
    base_params, 'pinn', config.tire_model_name, config.project_root);
base_params.tire.model_dir = fullfile('output', 'tire_models', config.tire_model_name);
base_params.tire.model_manifest = fullfile(base_params.tire.model_dir, 'manifest.json');
active_schema.full_center = apply_fixed_reference_values( ...
    active_schema.full_center, schema, base_params);
compatibility = make_compatibility(config, schema, active_schema);

[run_dir, resume_data] = resolve_run_directory(config, compatibility);
prepare_run_directory(run_dir, config, schema, active_schema, compatibility);
lock_path = fullfile(run_dir, 'campaign.lock');
acquire_lock(lock_path);
lock_cleanup = onCleanup(@() release_lock(lock_path));

design_context = struct( ...
    'extra_tunable_specs', schema.extra_tunable_specs, ...
    'optimize_tire_selection', false, ...
    'tire_candidates', struct([]), ...
    'tire_var_index', []);
previous_elapsed_sec = 0.0;
if ~isempty(resume_data) && isfield(resume_data, 'elapsed_time_sec')
    previous_elapsed_sec = resume_data.elapsed_time_sec;
end
remaining_time_sec = config.ga_max_time_sec - previous_elapsed_sec;
if remaining_time_sec <= 0
    error('run_full_vehicle_ga:timeBudgetExhausted', ...
        'The checkpoint has exhausted the configured GA time budget.');
end
context = struct( ...
    'config', config, ...
    'run_dir', run_dir, ...
    'base_params', base_params, ...
    'design_context', design_context, ...
    'active_schema', active_schema, ...
    'target_distance', 1006.2611818354848, ...
    'compatibility', compatibility, ...
    'campaign_elapsed_before_sec', previous_elapsed_sec, ...
    'segment_started_tic', tic);

pool = gcp('nocreate');
if isempty(pool) || pool.NumWorkers ~= config.parallel_workers
    if ~isempty(pool)
        delete(pool);
    end
    parpool('Processes', config.parallel_workers);
end

rng(config.random_seed, 'twister');
completed_generations = 0;
if ~isempty(resume_data)
    rng(resume_data.rng_state);
    initial_population = resume_data.population;
    initial_scores = resume_data.scores;
    completed_generations = resume_data.generation;
else
    [full_seeds, seed_report] = collect_vehicle_ga_seeds(config.seed_paths, schema);
    initial_population = full_seeds(:, active_schema.indices);
    initial_population = initial_population(1:min(size(initial_population, 1), ...
        config.population_size), :);
    initial_scores = [];
    write_json_atomic(fullfile(run_dir, 'seeds', 'import_report.json'), seed_report);
end

remaining_generations = max(1, config.max_generations - completed_generations);
output_function = @(options, state, flag) vehicle_ga_checkpoint_output( ...
    options, state, flag, context);
options = optimoptions('ga', ...
    'Display', 'iter', ...
    'PopulationSize', config.population_size, ...
    'MaxGenerations', remaining_generations, ...
    'MaxTime', remaining_time_sec, ...
    'MaxStallGenerations', remaining_generations, ...
    'UseParallel', false, ...
    'UseVectorized', true, ...
    'InitialPopulationMatrix', initial_population, ...
    'OutputFcn', output_function, ...
    'PlotFcn', []);
if ~isempty(initial_scores)
    options.InitialScoresMatrix = initial_scores;
end

objective = @(population) vehicle_ga_objective_batch(population, context);
lower = active_schema.variable_bounds(:, 1);
upper = active_schema.variable_bounds(:, 2);
started = tic;
[best_active, best_cost, exitflag, ga_output, final_population, final_scores] = ga( ...
    objective, numel(active_schema.indices), [], [], [], [], lower, upper, [], options);
elapsed = toc(started);
campaign_elapsed = previous_elapsed_sec + elapsed;

best_full = active_schema.full_center;
best_full(active_schema.indices) = best_active;
damper_f = find(strcmp(schema.variable_names, 'DamperF'), 1);
damper_r = find(strcmp(schema.variable_names, 'DamperR'), 1);
best_full(damper_r) = best_full(damper_f);
best_params = apply_full_design(base_params, best_full, design_context);
best_params.drs.enabled = false;
best_params.tire.model_dir = fullfile('output', 'tire_models', config.tire_model_name);
best_params.tire.model_manifest = fullfile(best_params.tire.model_dir, 'manifest.json');

final_record = evaluate_vehicle_ga_candidate( ...
    best_full, context, 'final_best_validation', fullfile(run_dir, 'best'), ...
    fullfile(run_dir, 'best', 'best_trace.csv'));

stage = struct( ...
    'name', 'run_full_vehicle_ga', ...
    'optimizer', 'ga', ...
    'event', config.target_event, ...
    'driver_mode', config.driver_mode, ...
    'lpv_model', config.lpv_model, ...
    'design_schema', schema.version, ...
    'design_vector', best_full, ...
    'variable_names', {schema.variable_names}, ...
    'active_variable_names', {active_schema.variable_names}, ...
    'fixed_variable_names', {active_schema.fixed_variable_names}, ...
    'objective_value', best_cost, ...
    'elapsed_time_sec', campaign_elapsed, ...
    'segment_elapsed_time_sec', elapsed, ...
    'exitflag', exitflag, ...
    'ga_output', ga_output, ...
    'selected_tire_model', selected_tire.name, ...
    'result', final_record.result, ...
    'accepted', final_record.gate.passed);
artifact = build_vehicle_artifact(best_params, 'stage_entry', stage);
artifact.design_vector = best_full;
artifact.variable_names = schema.variable_names;
artifact.optimizer_schema_version = schema.version;
best_path = fullfile(run_dir, 'best', 'best_vehicle_artifact.json');
save_vehicle_artifact(best_path, artifact);
if final_record.gate.passed
    copyfile(best_path, fullfile(config.output_root, 'latest_best_vehicle_artifact.json'), 'f');
end

result = struct( ...
    'schema_version', 'vehicle_ga_run/v1', ...
    'run_dir', run_dir, ...
    'best_cost', best_cost, ...
    'best_design_vector', best_full, ...
    'accepted', final_record.gate.passed, ...
    'exitflag', exitflag, ...
    'elapsed_time_sec', campaign_elapsed, ...
    'segment_elapsed_time_sec', elapsed, ...
    'completed_generations', completed_generations + ga_output.generations, ...
    'population', final_population, ...
    'scores', final_scores, ...
    'best_artifact', best_path);
write_json_atomic(fullfile(run_dir, 'run_summary.json'), rmfield(result, {'population', 'scores'}));
clear lock_cleanup;
end

function config = validate_config(config)
if ~strcmp(config.target_event, 'autocross') || ~strcmp(config.track_name, 'autocross')
    error('run_full_vehicle_ga:unsupportedEvent', ...
        'The validated LPV vehicle GA currently supports autocross only.');
end
if ~strcmp(config.driver_mode, 'lpv_lqr') || ~strcmp(config.lpv_model, 'steering6')
    error('run_full_vehicle_ga:invalidDriver', ...
        'driver_mode=lpv_lqr and lpv_model=steering6 are required.');
end
if config.drs_enabled
    error('run_full_vehicle_ga:unsupportedDrs', ...
        'DRS is disabled until the LPV driver has a validated DRS policy.');
end
positive_integer_fields = {'population_size', 'max_generations', 'parallel_workers'};
for i = 1:numel(positive_integer_fields)
    name = positive_integer_fields{i};
    value = config.(name);
    if ~isscalar(value) || value < 1 || value ~= floor(value)
        error('run_full_vehicle_ga:invalidConfig', '%s must be a positive integer.', name);
    end
end
if config.ga_max_time_sec <= 0 || config.ga_max_time_sec > config.wall_time_sec
    error('run_full_vehicle_ga:invalidTimeBudget', ...
        'ga_max_time_sec must be positive and no greater than wall_time_sec.');
end
if ~isfile(config.binary_path)
    error('run_full_vehicle_ga:missingBinary', ...
        'Release laptime_sim was not found: %s', config.binary_path);
end
tire_manifest_path = fullfile(config.project_root, 'output', 'tire_models', ...
    config.tire_model_name, 'manifest.json');
if ~isfile(tire_manifest_path)
    error('run_full_vehicle_ga:missingTireManifest', ...
        'Deployable PINN manifest was not found: %s', tire_manifest_path);
end
if config.quick_mode
    config.population_size = min(config.population_size, 4);
    config.max_generations = min(config.max_generations, 1);
    config.parallel_workers = min(config.parallel_workers, 2);
    config.ga_max_time_sec = min(config.ga_max_time_sec, 300);
    config.wall_time_sec = min(config.wall_time_sec, 360);
end
end

function compatibility = make_compatibility(config, schema, active)
binary_info = dir(config.binary_path);
manifest_path = fullfile(config.project_root, 'output', 'tire_models', ...
    config.tire_model_name, 'manifest.json');
manifest_info = dir(manifest_path);
compatibility = struct( ...
    'schema_version', schema.version, ...
    'variable_names', {schema.variable_names}, ...
    'variable_bounds', schema.variable_bounds, ...
    'active_variable_names', {active.variable_names}, ...
    'active_variable_indices', active.indices, ...
    'fixed_reference', active.full_center, ...
    'population_size', config.population_size, ...
    'max_generations', config.max_generations, ...
    'parallel_workers', config.parallel_workers, ...
    'ga_max_time_sec', config.ga_max_time_sec, ...
    'driver_mode', config.driver_mode, ...
    'lpv_model', config.lpv_model, ...
    'tire_model_name', config.tire_model_name, ...
    'track_name', config.track_name, ...
    'simulation_time_sec', config.simulation_time_sec, ...
    'initial_speed_mps', config.initial_speed_mps, ...
    'binary_bytes', binary_info.bytes, ...
    'binary_timestamp', binary_info.datenum, ...
    'tire_manifest_bytes', manifest_info.bytes, ...
    'tire_manifest_timestamp', manifest_info.datenum, ...
    'torque_contract', [true, 0.02, 4.5, 0.3, 0.3, 25.0], ...
    'objective_version', 'lpv_vehicle_ga_gate/v3');
end

function vector = apply_fixed_reference_values(vector, schema, base_params)
vector = set_named(vector, schema, 'TireFzNom', base_params.tire.Fz_nom);
vector = set_named(vector, schema, 'TireRelaxationLx', base_params.tire.relaxation.Lx_base);
vector = set_named(vector, schema, 'TireRelaxationLy', base_params.tire.relaxation.Ly_base);
vector = set_named(vector, schema, 'TireCx', base_params.tire.Cx);
vector = set_named(vector, schema, 'TireCy', base_params.tire.Cy);
vector = set_named(vector, schema, 'TireVerticalK', base_params.tire.k_tire);
vector = set_named(vector, schema, 'TireVerticalC', base_params.tire.c_tire);
end

function vector = set_named(vector, schema, name, value)
index = find(strcmp(schema.variable_names, name), 1);
vector(index) = value;
end

function [run_dir, resume_data] = resolve_run_directory(config, compatibility)
resume_data = [];
if isempty(config.resume_checkpoint)
    run_dir = fullfile(config.output_root, config.run_id);
    return;
end
checkpoint_path = char(config.resume_checkpoint);
loaded = load(checkpoint_path, 'checkpoint');
if ~isfield(loaded, 'checkpoint') || ~isequaln(loaded.checkpoint.compatibility, compatibility)
    error('run_full_vehicle_ga:incompatibleCheckpoint', ...
        'Checkpoint does not match the current GA physics/configuration contract.');
end
resume_data = loaded.checkpoint;
run_dir = fileparts(fileparts(checkpoint_path));
if isfile(fullfile(run_dir, 'run_summary.json'))
    error('run_full_vehicle_ga:campaignComplete', ...
        'The selected campaign already has a run_summary.json; start a new run instead.');
end
end

function prepare_run_directory(run_dir, config, schema, active, compatibility)
subdirs = {'checkpoint', 'evaluations', 'seeds', 'best'};
for i = 1:numel(subdirs)
    path = fullfile(run_dir, subdirs{i});
    if ~isfolder(path)
        mkdir(path);
    end
end
manifest = struct( ...
    'schema_version', 'vehicle_ga_manifest/v1', ...
    'created_at', char(datetime('now', 'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'config', config, ...
    'optimizer_schema', schema.version, ...
    'active_variable_names', {active.variable_names}, ...
    'fixed_variable_names', {active.fixed_variable_names}, ...
    'compatibility', compatibility);
write_json_atomic(fullfile(run_dir, 'manifest.json'), manifest);
end

function acquire_lock(lock_path)
lock_file = java.io.File(lock_path);
if ~lock_file.createNewFile()
    error('run_full_vehicle_ga:campaignLocked', ...
        'A campaign lock already exists: %s', lock_path);
end
fid = fopen(lock_path, 'w');
if fid == -1
    delete(lock_path);
    error('run_full_vehicle_ga:lockFailed', 'Cannot create %s.', lock_path);
end
fprintf(fid, '%d\n', feature('getpid'));
fclose(fid);
end

function release_lock(lock_path)
if isfile(lock_path)
    delete(lock_path);
end
end

function write_json_atomic(path, value)
staging = [path, '.writing'];
fid = fopen(staging, 'w');
if fid == -1
    error('run_full_vehicle_ga:writeFailed', 'Cannot write %s.', staging);
end
cleanup = onCleanup(@() close_if_open(fid));
fwrite(fid, jsonencode(value, 'PrettyPrint', true), 'char');
fclose(fid);
clear cleanup;
movefile(staging, path, 'f');
end

function close_if_open(fid)
try
    fclose(fid);
catch
end
end
