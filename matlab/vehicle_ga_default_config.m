function config = vehicle_ga_default_config(project_root)
% VEHICLE_GA_DEFAULT_CONFIG Canonical long-running full-vehicle GA settings.

if nargin < 1 || isempty(project_root)
    project_root = fileparts(fileparts(mfilename('fullpath')));
end

timestamp = char(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
config = struct( ...
    'project_root', char(project_root), ...
    'run_id', ['lpv_vehicle_ga_', timestamp], ...
    'target_event', 'autocross', ...
    'track_name', 'autocross', ...
    'track_radius', 0.0, ...
    'simulation_time_sec', 180.0, ...
    'initial_speed_mps', 6.0, ...
    'driver_mode', 'lpv_lqr', ...
    'lpv_model', 'steering6', ...
    'tire_model_name', 'Hoosier_18p0X6p0-10_R20_Rim6', ...
    'population_size', 80, ...
    'max_generations', 55, ...
    'parallel_workers', 10, ...
    'wall_time_sec', 5 * 3600, ...
    'ga_max_time_sec', 4 * 3600 + 55 * 60, ...
    'random_seed', 20260722, ...
    'drs_enabled', false, ...
    'resume_checkpoint', '', ...
    'quick_mode', false, ...
    'output_root', fullfile(project_root, 'output', 'vehicle_ga_runs'), ...
    'binary_path', fullfile(project_root, 'build', 'cpp', 'laptime_sim'), ...
    'candidate_timeout_sec', 180, ...
    'use_lpv_ggv', true, ...
    'suspension_design', 'kc', ...
    'freeze_variables', {{}}, ...       % e.g. vehicle_ga_low_sensitivity_variables()
    'fixed_reference_path', '', ...     % artifact whose values the frozen variables take
    'ggv_cache_dir', fullfile(project_root, 'output', 'vehicle_ga_runs', 'ggv_cache'), ...
    'use_tire_lut', true, ...
    'tire_lut_file', '', ...
    'seed_paths', {{ ...
        fullfile(project_root, 'matlab', 'parameter_presets', 'params_winged_flexible.json'), ...
        fullfile(project_root, 'matlab', 'optimized_skidpad.json'), ...
        fullfile(project_root, 'matlab', 'optimized_autocross.json'), ...
        fullfile(project_root, 'matlab', 'optimized_acceleration.json'), ...
        fullfile(project_root, 'matlab', 'optimized_autocrossDRS.json') ...
    }});
end
