function main_steering_optimizer(json_file, run_options)
% MAIN_STEERING_OPTIMIZER (Layer 1.5)
%
% Reads front hardpoints from the unified vehicle artifact and appends
% tie-rod hardpoints back into the same JSON.

fprintf('================================================================\n');
fprintf(' Layer 1.5: Steering Kinematics Optimizer\n');
fprintf('================================================================\n');

helper_dir = fileparts(fileparts(mfilename('fullpath')));
if exist('load_vehicle_artifact', 'file') ~= 2
    addpath(helper_dir);
end
susp_dir = fullfile(helper_dir, '..', 'suspension_kinematics_design');
if exist('evaluate_double_wishbone_3d', 'file') ~= 2 && exist(susp_dir, 'dir')
    addpath(susp_dir);
end

if nargin < 2 || isempty(run_options)
    run_options = struct();
end
if ~isfield(run_options, 'rng_seed')
    run_options.rng_seed = 42;
end
if ~isfield(run_options, 'n_starts')
    run_options.n_starts = 20;
end
if ~isfield(run_options, 'rack_travel_max')
    run_options.rack_travel_max = 0.03;
end
if ~isfield(run_options, 'tie_rod_length_min')
    run_options.tie_rod_length_min = 0.15;
end
if ~isfield(run_options, 'tie_rod_length_max')
    run_options.tie_rod_length_max = 0.45;
end
if ~isfield(run_options, 'rod_end_angle_max')
    run_options.rod_end_angle_max = deg2rad(30.0);
end
if ~isfield(run_options, 'ackermann_tolerance')
    run_options.ackermann_tolerance = deg2rad(0.5);
end
if ~isfield(run_options, 'bump_tolerance')
    run_options.bump_tolerance = 0.005;
end
rng(run_options.rng_seed, 'twister');

if nargin < 1
    json_file = resolve_default_vehicle_json(fullfile(helper_dir, '..'), ...
        'RequireExportReady', true, ...
        'RequireSuspensionHardpoints', true, ...
        'RequiredHardpointCorners', {'FL'});
    if isempty(json_file)
        error('No vehicle artifact with suspension hardpoints found.');
    end
end

vehicle_data = load_vehicle_artifact(json_file);
p = merge_nested_structs(create_vehicle_baseline_template(), vehicle_data.params);

if ~isfield(p, 'suspension') || ~isfield(p.suspension, 'kc') || ~isfield(p.suspension.kc, 'corners') ...
        || ~isfield(p.suspension.kc.corners, 'FL') || ~isfield(p.suspension.kc.corners.FL, 'hardpoints')
    error('Front suspension KC hardpoints must exist in the artifact before running steering optimization.');
end

hp = p.suspension.kc.corners.FL.hardpoints;
fl_geom = struct();
fl_geom.upper_arm_upright = hp.upper_ball_joint(:);
fl_geom.lower_arm_upright = hp.lower_ball_joint(:);
fl_geom.wheel_center = hp.wheel_center(:);

axle = resolve_axle_geometry(p, struct(), 'front');
R_tire = axle.R_tire;
R_loaded = axle.R_loaded;
build_eval_geom = @(hp_, is_left, camber) geom_from_hardpoints(rmfield_if(hp_, ...
    {'tie_rod_inner', 'tie_rod_outer'}), is_left, true, camber, R_tire, R_loaded);
fl_base_geom = build_eval_geom(hp, true, p.suspension.static_camber(1));
if ~isfield(p.suspension.kc.corners, 'FR') || ~isfield(p.suspension.kc.corners.FR, 'hardpoints')
    error('Steering:MissingFRHardpoints', ...
        'FR hardpoints are required for the left/right Ackermann sweep.');
end
fr_base_geom = build_eval_geom(p.suspension.kc.corners.FR.hardpoints, false, ...
    p.suspension.static_camber(2));

min_moment_arm = 0.065;

L_U = fl_geom.lower_arm_upright;
W_C = fl_geom.wheel_center;

x_rack_nominal = W_C(1) + 0.100;
lb = [x_rack_nominal - 0.100, -0.450, -0.200, W_C(1) + 0.020, W_C(2) - 0.080, -0.200];
ub = [x_rack_nominal + 0.100, -0.150, -0.050, W_C(1) + 0.150, W_C(2) + 0.100, 0.050];
x0 = [x_rack_nominal, -0.300, -0.100, x_rack_nominal, L_U(2) - 0.010, -0.100];

options = optimoptions('fmincon', 'Display', 'iter', 'Algorithm', 'sqp', ...
    'StepTolerance', 1e-12, 'ConstraintTolerance', 1e-6);

use_cache = ~isfield(run_options, 'use_cache') || run_options.use_cache;
if use_cache
    steer_cache = containers.Map('KeyType', 'char', 'ValueType', 'double');
else
    steer_cache = [];
end
obj_fun = @(x) steer_cost(x, fl_base_geom, fr_base_geom, fl_geom, p, min_moment_arm, run_options, steer_cache);
problem = createOptimProblem('fmincon', 'objective', obj_fun, 'x0', x0, ...
    'lb', lb, 'ub', ub, 'options', options);

ms = MultiStart('Display', 'none');
fprintf('Optimizing Tie-Rod points...\n');
[x_opt, fval, exitflag, ~, ms_solutions] = run(ms, problem, run_options.n_starts);
if exitflag <= 0
    error('Steering optimization did not converge (MultiStart exitflag=%d); refusing to save.', exitflag);
end

[bump_steer_err, act_moment_arm, bump_proxy_err, bump_converged, ...
    feasibility] = eval_steering_candidate(x_opt, fl_base_geom, fr_base_geom, ...
    fl_geom, p, run_options);
if ~bump_converged
    error('Steering:ClosedLinkKCFailed', ...
        'Closed-link bump-steer evaluation did not converge for the optimized tie rod.');
end
if ~feasibility.ok
    warning('Steering:InfeasibleHardpoints', ...
        'Optimized tie rod violates steering feasibility checks; saving with provisional quality.');
end

fprintf('\nFinal Performance:\n');
fprintf('  Bump Steer (3D):    %.5f rad\n', bump_steer_err);
fprintf('  Bump Steer (proxy): %.5f\n', bump_proxy_err);
fprintf('  Ackermann error:    %.3f deg (tol %.3f deg)\n', ...
    rad2deg(feasibility.ackermann_error_rad), rad2deg(feasibility.ackermann_tolerance_rad));
fprintf('  Tie rod length:     %.1f mm (%.0f..%.0f mm)\n', ...
    feasibility.tie_rod_length_m * 1000, ...
    feasibility.tie_rod_length_bounds_m(1) * 1000, ...
    feasibility.tie_rod_length_bounds_m(2) * 1000);
fprintf('  Rod end angle:      %.1f deg (max %.1f deg)\n', ...
    rad2deg(feasibility.rod_end_angle_rad), rad2deg(feasibility.rod_end_angle_max_rad));
fprintf('  Moment Arm:         %.1f mm (Target: >= %.1f mm)\n', act_moment_arm * 1000, min_moment_arm * 1000);
fprintf('  Exitflag:           %d\n', exitflag);

params_update = p;
hp_fl = params_update.suspension.kc.corners.FL.hardpoints;
hp_fr = params_update.suspension.kc.corners.FR.hardpoints;
hp_fl.tie_rod_inner = x_opt(1:3);
hp_fl.tie_rod_outer = x_opt(4:6);
hp_fr.tie_rod_inner = [x_opt(1), -x_opt(2), x_opt(3)];
hp_fr.tie_rod_outer = [x_opt(4), -x_opt(5), x_opt(6)];

% Full closed-link refresh (#42): every kinematics field (camber, roll gain,
% jacking, anti, compliance, samples) is re-solved with the tie rod and the
% whole corner block is rewritten, not just the toe fields.
dense = kc_dense_samples(p, suspension_design_space(p, 'front'));
dense.RackSamples = linspace(-run_options.rack_travel_max, run_options.rack_travel_max, ...
    numel(dense.RackSamples));
dense.SteerMapTravelSamples = dense.TravelSamples(1:2:end);   % 2x the dense step
fl_geom_eval = geom_from_hardpoints(hp_fl, true, true, p.suspension.static_camber(1), R_tire, R_loaded);
fr_geom_eval = geom_from_hardpoints(hp_fr, false, true, p.suspension.static_camber(2), R_tire, R_loaded);
metrics_fl = evaluate_closed_link(fl_geom_eval, p, 1, dense);
metrics_fr = evaluate_closed_link(fr_geom_eval, p, 2, dense);
if ~metrics_fl.converged || ~metrics_fr.converged
    error('Steering:ClosedLinkKCFailed', ...
        'Tie-rod-constrained K&C solve did not converge; refusing to save unverified toe curves.');
end
if (~metrics_fl.polyfit_quality.fit_ok || ~metrics_fr.polyfit_quality.fit_ok) ...
        && ~(isfield(run_options, 'allow_poor_fit') && run_options.allow_poor_fit)
    error('KC:PoorPolyfit', ['Front closed-link quadratic K&C fits exceed tolerance ', ...
        '(polyfit_quality.fit_ok=false); pass run_options.allow_poor_fit=true to save as provisional.']);
end
script = 'matlab/steering_hardpoint_design/main_steering_optimizer.m';
params_update.suspension.kc.corners.FL = build_corner_kc(fl_geom_eval, metrics_fl, ...
    p.suspension.static_toe(1), p.suspension.static_camber(1), script, feasibility.failed_checks);
params_update.suspension.kc.corners.FR = build_corner_kc(fr_geom_eval, metrics_fr, ...
    p.suspension.static_toe(2), p.suspension.static_camber(2), script, feasibility.failed_checks);
params_update.suspension.kc.front = build_axle_kc(metrics_fl, p.suspension.motion_ratio(1:2), true);
% Rack -> (delta_L, delta_R) map (#43): replaces the scalar Ackermann blend at runtime.
params_update.suspension.kc.steer_map = struct( ...
    'schema_version', 'kc_steer_map/v1', ...
    'rack_travel_m', metrics_fl.steer_map.rack_travel_m, ...
    'wheel_travel_m', metrics_fl.steer_map.wheel_travel_m, ...
    'delta_L_rad', metrics_fl.steer_map.steer_rad, ...
    'delta_R_rad', metrics_fr.steer_map.steer_rad, ...
    'layout', 'delta_X_rad[i_wheel_travel][j_rack]; delta_L uses FL travel, delta_R uses FR travel', ...
    'bump_steer', 'removed (rack=0 column); add kinematics.toe_vs_travel separately', ...
    'rack_ratio_m_per_rad', p.steering.rack_ratio, ...
    'source', script);

if ~isfield(params_update, 'suspension_geometry') || ~isstruct(params_update.suspension_geometry)
    params_update.suspension_geometry = struct();
end
params_update.suspension_geometry.front_steering = struct( ...
    'schema_version', 'suspension_geometry/v1', ...
    'updated_at', datestr(now, 'yyyy-mm-dd HH:MM:SS'), ...
    'source_script', 'matlab/steering_hardpoint_design/main_steering_optimizer.m', ...
    'optimizer', 'MultiStart/fmincon/sqp', ...
    'solver_options', struct('Algorithm', 'sqp', 'StepTolerance', 1e-12, ...
        'ConstraintTolerance', 1e-6, 'MultiStartDisplay', 'none', 'UseParallel', false), ...
    'code_version', get_code_version(helper_dir), ...
    'n_starts', run_options.n_starts, ...
    'random_seed', run_options.rng_seed, ...
    'optimizer_cost', fval, ...
    'optimizer_diagnostics', struct( ...
        'local_exitflags', [ms_solutions.Exitflag], ...
        'n_local_starts', numel(ms_solutions), ...
        'n_local_converged', sum([ms_solutions.Exitflag] > 0), ...
        'evaluation_cache_entries', cache_count(steer_cache), ...
        'evaluation_cache_enabled', use_cache), ...
    'design_vector', x_opt(:)', ...
    'bounds_lb', lb, ...
    'bounds_ub', ub, ...
    'targets', struct('min_moment_arm_m', min_moment_arm), ...
    'target_sources', struct( ...
        'min_moment_arm_m', 'design_target', ...
        'bump_steer_penalty', 'closed_link_3d_travel'), ...
    'weights', struct('bump_steer', 10000.0, 'moment_arm', 1e6), ...
    'bump_steer_model', 'closed_link_3d', ...
    'bump_steer_travel_samples_m', bump_travel_samples(p), ...
    'feasibility', feasibility, ...
    'achieved', struct( ...
        'moment_arm_m', act_moment_arm, ...
        'bump_steer_penalty', bump_steer_err, ...
        'bump_steer_proxy_penalty', bump_proxy_err), ...
    'exitflag', exitflag);

stageResult = struct( ...
    'objective_value', fval, ...
    'moment_arm_m', act_moment_arm, ...
    'bump_steer_penalty', bump_steer_err, ...
    'bump_steer_proxy_penalty', bump_proxy_err, ...
    'bump_steer_model', 'closed_link_3d', ...
    'feasibility', feasibility, ...
    'exitflag', exitflag);

save_suspension_geometry_artifact( ...
    'BaseArtifactPath', json_file, ...
    'InPlace', true, ...
    'CurrentParams', params_update, ...
    'StageName', 'suspension_geometry_front_steering', ...
    'StageOptimizer', 'multistart_fmincon', ...
    'StageResult', stageResult);

fprintf('\nSteering hardpoints appended to %s successfully!\n', json_file);
end

function metrics = evaluate_closed_link(geom, p, wheelIdx, samples)
args = namedargs2cell(samples);
metrics = evaluate_double_wishbone_3d(geom, ...
    'TrackWidth', p.mass.track_f, ...
    'Wheelbase', p.mass.wheelbase, ...
    'CGHeight', p.mass.h_cg, ...
    'CGToAxle', p.mass.a, ...
    'BrakeBiasFront', p.brake.balance, ...
    'DriveBiasRear', 1.0, ...
    'StaticToe', p.suspension.static_toe(wheelIdx), ...
    'StaticCamber', 0.0, ...
    'SteeringStiffness', p.steering.stiffness, ...
    'ResidualTolerance', 5e-4, ...
    'UseTieRod', true, ...
    args{:});
end

function s = rmfield_if(s, names)
s = rmfield(s, intersect(fieldnames(s), names));
end

function [bump_error, moment_arm] = eval_steer(x, fl_geom)
TR_C = [x(1); x(2); x(3)];
TR_U = [x(4); x(5); x(6)];

U_U = fl_geom.upper_arm_upright;
L_U = fl_geom.lower_arm_upright;

kp_axis = U_U - L_U;
kp_dir = kp_axis / norm(kp_axis);
v = TR_U - L_U;
proj = dot(v, kp_dir) * kp_dir;
moment_arm = norm(v - proj);

dz = -0.025;
TR_U_bumped_ideal = TR_U + [0; 0; dz];
L_TR = norm(TR_U - TR_C);
L_TR_bumped = norm(TR_U_bumped_ideal - TR_C);
d_error = L_TR_bumped - L_TR;
bump_error = abs(d_error / max(moment_arm, 1e-6));

end

function cost = steer_cost(x, base_geom, fr_base_geom, fl_geom, params, min_moment_arm, opts, steer_cache)
use_cache = isa(steer_cache, 'containers.Map');
cache_key = sprintf('%.12g|', x(:));
if use_cache && isKey(steer_cache, cache_key)
    cost = steer_cache(cache_key);
    return;
end
[bump_error, act_moment_arm, ~, ~, feasibility] = ...
    eval_steering_candidate(x, base_geom, fr_base_geom, fl_geom, params, opts);

cost = (bump_error / max(opts.bump_tolerance, eps))^2;
ack_excess = max(0.0, feasibility.ackermann_error_rad - opts.ackermann_tolerance);
cost = cost + 1e6 * (ack_excess / max(opts.ackermann_tolerance, eps))^2;
steering_arm = abs(x(5) - fl_geom.lower_arm_upright(2));
cost = cost + ((steering_arm - 0.040) / 0.005)^2;
if ~isfinite(cost)
    cost = 1e12;
    return;
end
if act_moment_arm < min_moment_arm
    cost = cost + 1e6 * (min_moment_arm - act_moment_arm)^2;
end
if ~feasibility.tie_rod_length_ok
    cost = cost + 1e6 * feasibility.tie_rod_length_violation_m^2;
end
if ~feasibility.rod_end_angle_ok
    cost = cost + 1e6 * feasibility.rod_end_angle_violation_rad^2;
end
if ~feasibility.rack_travel_ok
    cost = cost + 1e6;
end
if ~feasibility.bump_ok
    cost = cost + 1e6;
end
if use_cache
    steer_cache(cache_key) = cost;
end
end

function [bump_error, moment_arm, proxy_error, bump_converged, feasibility] = ...
        eval_steering_candidate(x, base_geom, fr_base_geom, fl_geom, params, opts)
[bump_error, moment_arm, proxy_error, bump_converged] = ...
    eval_bump_3d(x, base_geom, fl_geom, params);
[ackermann_error, rack_ok, rod_end_angle] = ...
    eval_ackermann(x, base_geom, fr_base_geom, params, opts);

tie_rod_length = norm(x(4:6) - x(1:3));
tie_rod_length_ok = tie_rod_length >= opts.tie_rod_length_min ...
    && tie_rod_length <= opts.tie_rod_length_max;
tie_rod_length_violation = max([opts.tie_rod_length_min - tie_rod_length, ...
    tie_rod_length - opts.tie_rod_length_max, 0.0]);
rod_end_angle_ok = rod_end_angle <= opts.rod_end_angle_max;
rod_end_angle_violation = max(rod_end_angle - opts.rod_end_angle_max, 0.0);
ackermann_ok = ackermann_error <= opts.ackermann_tolerance;
bump_ok = bump_converged && bump_error <= opts.bump_tolerance;

failed_checks = {};
if ~rack_ok, failed_checks{end + 1} = 'rack_travel'; end
if ~tie_rod_length_ok, failed_checks{end + 1} = 'tie_rod_length'; end
if ~rod_end_angle_ok, failed_checks{end + 1} = 'rod_end_angle'; end
if ~ackermann_ok, failed_checks{end + 1} = 'ackermann'; end
if ~bump_ok, failed_checks{end + 1} = 'bump_steer'; end

feasibility = struct( ...
    'ok', rack_ok && tie_rod_length_ok && rod_end_angle_ok && ackermann_ok && bump_ok, ...
    'failed_checks', {failed_checks}, ...
    'ackermann_error_rad', ackermann_error, ...
    'ackermann_tolerance_rad', opts.ackermann_tolerance, ...
    'ackermann_ok', ackermann_ok, ...
    'rack_travel_max_m', opts.rack_travel_max, ...
    'rack_travel_ok', rack_ok, ...
    'tie_rod_length_m', tie_rod_length, ...
    'tie_rod_length_bounds_m', [opts.tie_rod_length_min, opts.tie_rod_length_max], ...
    'tie_rod_length_ok', tie_rod_length_ok, ...
    'tie_rod_length_violation_m', tie_rod_length_violation, ...
    'rod_end_angle_rad', rod_end_angle, ...
    'rod_end_angle_max_rad', opts.rod_end_angle_max, ...
    'rod_end_angle_ok', rod_end_angle_ok, ...
    'rod_end_angle_violation_rad', rod_end_angle_violation, ...
    'bump_steer_3d_rad', bump_error, ...
    'bump_steer_tolerance_rad', opts.bump_tolerance, ...
    'bump_ok', bump_ok);
end

function [ackermann_error, rack_ok, rod_end_angle] = ...
        eval_ackermann(x, fl_base_geom, fr_base_geom, params, opts)
rack_samples = [-opts.rack_travel_max, 0.0, opts.rack_travel_max];
fl_geom = fl_base_geom;
fl_geom.tie_rod_chassis = reshape(x(1:3), 3, 1);
fl_geom.tie_rod_upright = reshape(x(4:6), 3, 1);
fr_geom = fr_base_geom;
fr_geom.tie_rod_chassis = reshape([x(1), -x(2), x(3)], 3, 1);
fr_geom.tie_rod_upright = reshape([x(4), -x(5), x(6)], 3, 1);

fl_metrics = evaluate_double_wishbone_3d(fl_geom, ...
    'TrackWidth', params.mass.track_f, ...
    'Wheelbase', params.mass.wheelbase, ...
    'CGHeight', params.mass.h_cg, ...
    'CGToAxle', params.mass.a, ...
    'StaticToe', params.suspension.static_toe(1), ...
    'StaticCamber', 0.0, ...
    'SteeringStiffness', params.steering.stiffness, ...
    'TravelSamples', 0.0, ...
    'RollSamples', 0.0, ...
    'SteerSamples', 0.0, ...
    'RackSamples', rack_samples, ...
    'ResidualTolerance', 5e-4, ...
    'UseTieRod', true);
fr_metrics = evaluate_double_wishbone_3d(fr_geom, ...
    'TrackWidth', params.mass.track_f, ...
    'Wheelbase', params.mass.wheelbase, ...
    'CGHeight', params.mass.h_cg, ...
    'CGToAxle', params.mass.a, ...
    'StaticToe', params.suspension.static_toe(2), ...
    'StaticCamber', 0.0, ...
    'SteeringStiffness', params.steering.stiffness, ...
    'TravelSamples', 0.0, ...
    'RollSamples', 0.0, ...
    'SteerSamples', 0.0, ...
    'RackSamples', rack_samples, ...
    'ResidualTolerance', 5e-4, ...
    'UseTieRod', true);

rack_ok = fl_metrics.converged && fr_metrics.converged;
ackermann_error = pi;
if rack_ok
    d_left = fl_metrics.steer_samples;
    d_right = fr_metrics.steer_samples;
    errors = zeros(size(rack_samples));
    for i = 1:numel(rack_samples)
        if d_left(i) > 0
            inner = abs(d_left(i));
            outer = abs(d_right(i));
        else
            inner = abs(d_right(i));
            outer = abs(d_left(i));
        end
        if inner < deg2rad(0.2)
            errors(i) = 0.0;
            continue;
        end
        ideal_outer = atan(1.0 / (cot(inner) + params.mass.track_f / params.mass.wheelbase));
        errors(i) = abs(outer - ideal_outer);
    end
    ackermann_error = max(errors);
end

dir0 = tie_rod_direction(x, 0.0);
rod_end_angle = 0.0;
for d = rack_samples
    dir = tie_rod_direction(x, d);
    rod_end_angle = max(rod_end_angle, acos(max(-1.0, min(1.0, abs(dot(dir, dir0))))));
end
end

function dir = tie_rod_direction(x, rack_displacement)
inner = [x(1); x(2) + rack_displacement; x(3)];
outer = [x(4); x(5); x(6)];
dir = (outer - inner) / max(norm(outer - inner), 1e-9);
end

function [bump_error, moment_arm, proxy_error, converged] = ...
        eval_bump_3d(x, base_geom, fl_geom, params)
geom = base_geom;
geom.tie_rod_chassis = reshape(x(1:3), 3, 1);
geom.tie_rod_upright = reshape(x(4:6), 3, 1);
metrics = evaluate_double_wishbone_3d(geom, ...
    'TrackWidth', params.mass.track_f, ...
    'Wheelbase', params.mass.wheelbase, ...
    'CGHeight', params.mass.h_cg, ...
    'CGToAxle', params.mass.a, ...
    'StaticToe', params.suspension.static_toe(1), ...
    'StaticCamber', 0.0, ...
    'SteeringStiffness', params.steering.stiffness, ...
    'UseTieRod', true, ...
    'TravelSamples', bump_travel_samples(params), ...
    'RackSamples', 0.0, ...
    'SteerSamples', 0.0, ...
    'RollSamples', 0.0);
[proxy_error, moment_arm] = eval_steer(x, fl_geom);
converged = metrics.converged;
if ~converged
    bump_error = 1.0;
    return;
end
toe = metrics.travel_toe_curve(:);
zero_idx = find(abs(metrics.travel_samples) < 1e-12, 1);
if isempty(zero_idx)
    zero_idx = 1;
end
bump_error = max(abs(toe - toe(zero_idx)));
end

function z = bump_travel_samples(params)
% 11-point bump-steer objective over the bump-stop range + 10 mm (#40).
half = params.suspension.bump_stop_gap + 0.010;
z = linspace(-half, half, 11);
end

function n = cache_count(cache)
if isempty(cache)
    n = 0;
else
    n = cache.Count;
end
end
