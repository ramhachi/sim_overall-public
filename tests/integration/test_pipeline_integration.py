import subprocess
import shlex
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[2]
IN_DOCKER_WORKSPACE = REPO_ROOT == Path("/workspace")


def run_laptime_command(sim_cmd):
    if IN_DOCKER_WORKSPACE:
        test_cmd = ["bash", "-c", sim_cmd]
    else:
        test_cmd = [
            "docker", "compose", "-f", "docker-compose.yml", "run", "--rm", "fsae-sim",
            "bash", "-c", sim_cmd
        ]

    print(f"Executing: {' '.join(test_cmd)}")
    completed = subprocess.run(
        test_cmd,
        cwd=REPO_ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    print(completed.stdout)
    print(completed.stderr)
    return completed


def test_integration():
    # Mimic the command generated by optimize_pid_gains.m for ASE_autocross
    # target_dist = 1000.0 logic is internal to MATLAB, but the command is crucial
    # A 5 s run cannot complete the 1000 m course, so the expected contract is
    # fail-fast with an explicit DNF status rather than a misleading success.
    
    # optimize_pid_gains('ASE_autocross', 0, 180, 5.0, 30)
    
    track_file_arg = "/workspace/data/ASE_autocross_sim.csv"
    track_radius = 0.0
    sim_time = 5.0 # Short time for test
    initial_speed = 5.0
    
    # Random gains (middle of range)
    kp_st = 1.0
    kd_st = 0.5
    ki_st = 0.1
    kh_st = 0.8
    kff_st = 1.0
    kp_sp = 0.5
    ki_sp = 0.1
    max_th = 0.5
    
    # Direct output to a known location to avoid path confusion
    # /workspace is the project root in the container
    output_path = "/workspace/opt_temp_test.csv"
    
    sim_cmd = (
        f'cd build && cmake --build . >/dev/null && ./cpp/laptime_sim --track {track_file_arg} --radius {track_radius} --time {sim_time} --initial-speed {initial_speed} '
        f'--kp-steer {kp_st} --kd-steer {kd_st} --ki-steer {ki_st} '
        f'--kh-steer {kh_st} --kff-steer {kff_st} '
        f'--kp-speed {kp_sp} --ki-speed {ki_sp} --max-throttle {max_th} '
        f'--output {output_path}'
    )
    
    completed = run_laptime_command(sim_cmd)

    assert completed.returncode == 1
    assert "Status: failed" in completed.stdout
    assert "Failure code: lap_not_completed" in completed.stdout


def test_laptime_rejects_invalid_tire_friction_params():
    params_json = '{"mu_x":0.0,"mu_y":0.0}'
    sim_cmd = (
        "cd build && cmake --build . >/dev/null && ./cpp/laptime_sim --track circle --radius 30 --time 0.01 "
        f"--params-json {shlex.quote(params_json)} --output_json"
    )

    completed = run_laptime_command(sim_cmd)

    assert completed.returncode == 1
    assert '"status":"failed"' in completed.stdout
    assert '"failure_code":"invalid_vehicle_params"' in completed.stdout
    assert "tire.mu_x_max" in completed.stdout

if __name__ == "__main__":
    test_integration()
