function main_a_arm_optimizer(json_file, run_options)
% MAIN_A_ARM_OPTIMIZER - Runtime-driven front double-wishbone inverse-analysis.

fprintf('================================================================\n');
fprintf(' A-Arm Kinematics Optimizer (Layer 1 & 2)\n');
fprintf('================================================================\n');

script_dir = fileparts(mfilename('fullpath'));
project_matlab_dir = fullfile(script_dir, '..', 'matlab');
if exist('load_vehicle_artifact', 'file') ~= 2
    addpath(project_matlab_dir);
end

if nargin < 2 || isempty(run_options)
    run_options = struct();
end
if ~isfield(run_options, 'rng_seed')
    run_options.rng_seed = 42;
end
if ~isfield(run_options, 'n_starts')
    run_options.n_starts = 50;
end
rng(run_options.rng_seed, 'twister');

if nargin < 1
    json_file = resolve_default_vehicle_json(fullfile(script_dir, '..'), 'RequireExportReady', true);
    if isempty(json_file)
        error('No vehicle artifact candidate found.');
    end
end
if ~isfile(json_file)
    error('Cannot find %s', json_file);
end

artifact = load_vehicle_artifact(json_file);
p = merge_nested_structs(create_vehicle_baseline_template(), artifact.params);
targets = build_inverse_targets(p, 'front');

axle = resolve_axle_geometry(p, run_options, 'front');
W_C = axle.W_C;
R_tire = axle.R_tire;
arm_x_offset = axle.arm_x_offset;
static_camber_deg = rad2deg(p.suspension.static_camber(1));

target_RC_Z = targets.roll_center_z;
target_KPI = targets.kpi_deg;
target_Caster = targets.caster_deg;
target_camber_gain = targets.camber_vs_travel(2);

fprintf('Targets Loaded from JSON:\n');
fprintf('  Track Width (Front):  %.3f m\n', p.mass.track_f);
fprintf('  Static Camber:        %.2f deg\n', static_camber_deg);
fprintf('  Target Camber Gain:   %.2f rad/m\n', target_camber_gain);
fprintf('  Target Roll Center Z: %.3f m\n', target_RC_Z);

max_upright_radius = 0.20;
min_kingpin_z_sep = 0.120;
fprintf('  Max Upright Radius:   %.3f m\n', max_upright_radius);
fprintf('  Min KP Z separation:  %.0f mm\n', min_kingpin_z_sep * 1000);

upright_x_max = 0.050;
L_U_local_z_max = 0.148;
U_U_local_z_max = L_U_local_z_max - min_kingpin_z_sep;
U_U_local_z_min = -R_tire;

lb = [
    -0.450, -0.400, ...
    -0.450, -0.200, ...
    -upright_x_max,  0.000,  U_U_local_z_min, ...
    -upright_x_max,  0.000, -0.050 ...
];

ub = [
    -0.300, -0.200, ...
    -0.300, -0.050, ...
     upright_x_max,  0.060,  U_U_local_z_max, ...
     upright_x_max,  0.060,  L_U_local_z_max ...
];

x0 = [
    -0.350, -0.285, ...
    -0.320, -0.150, ...
     0.010,  0.020, -0.120, ...
    -0.010,  0.020,  0.050 ...
];

options = optimoptions('fmincon', 'Display', 'off', 'Algorithm', 'sqp', ...
    'StepTolerance', 1e-12, 'ConstraintTolerance', 1e-6);

use_cache = ~isfield(run_options, 'use_cache') || run_options.use_cache;
if use_cache
    cost_cache = containers.Map('KeyType', 'char', 'ValueType', 'double');
else
    cost_cache = [];
end
obj_fun = @(x) cost_function(x, p, targets, W_C, R_tire, max_upright_radius, min_kingpin_z_sep, arm_x_offset, cost_cache);
nonlcon_fun = @(x) physical_constraints(x, W_C, R_tire, static_camber_deg, max_upright_radius, min_kingpin_z_sep, arm_x_offset);
problem = createOptimProblem('fmincon', 'objective', obj_fun, 'x0', x0, ...
    'lb', lb, 'ub', ub, 'options', options, 'nonlcon', nonlcon_fun);

ms = MultiStart('Display', 'iter', 'UseParallel', false);

fprintf('\nRunning Runtime-Driven Front Geometry Optimization (MultiStart)...\n');
t_opt_start = tic;
[x_opt, fval, exitflag, ~, ms_solutions] = run(ms, problem, run_options.n_starts);
optimizer_elapsed_s = toc(t_opt_start);
if exitflag <= 0
    error('Front A-arm optimization did not converge (MultiStart exitflag = %d).', exitflag);
end

geom_fl = build_geom(x_opt, W_C, R_tire, static_camber_deg, true, true, arm_x_offset);
metrics_fl = evaluate_metrics(geom_fl, p, p.suspension.static_toe(1), p.suspension.static_camber(1));
geom_fr = mirror_geom(geom_fl);
metrics_fr = evaluate_metrics(geom_fr, p, p.suspension.static_toe(2), p.suspension.static_camber(2));
if ~metrics_fl.converged || ~metrics_fr.converged
    error('Kinematics solve did not converge for the optimized front geometry.');
end

fprintf('\nFinal Performance:\n');
fprintf('  Roll Center Z:   %.3f m (Target: %.3f)\n', metrics_fl.roll_center_z, target_RC_Z);
fprintf('  KPI:             %.2f deg (Target: %.2f)\n', metrics_fl.kpi_deg, target_KPI);
fprintf('  Caster:          %.2f deg (Target: %.2f)\n', metrics_fl.caster_deg, target_Caster);
fprintf('  Scrub Radius:    %.3f m (Target: %.3f)\n', metrics_fl.scrub_radius_m, targets.scrub_radius_m);
fprintf('  Mech Trail:      %.3f m (Target: %.3f)\n', metrics_fl.mechanical_trail_m, targets.mechanical_trail_m);
fprintf('  Camber Gain:     %.2f rad/m (Target: %.2f)\n', metrics_fl.camber_gain_rad_m, target_camber_gain);

params_update = p;
params_update.suspension.kc.front = build_axle_kc(metrics_fl, p.suspension.motion_ratio(1:2), true);
params_update.suspension.kc.corners.FL = build_corner_kc(geom_fl, metrics_fl, p.suspension.static_toe(1), p.suspension.static_camber(1));
params_update.suspension.kc.corners.FR = build_corner_kc(geom_fr, metrics_fr, p.suspension.static_toe(2), p.suspension.static_camber(2));

suspensionGeometry = struct();
suspensionGeometry.front = struct( ...
    'schema_version', 'suspension_geometry/v1', ...
    'updated_at', datestr(now, 'yyyy-mm-dd HH:MM:SS'), ...
    'source_script', 'suspension_kinematics_design/main_a_arm_optimizer.m', ...
    'axle_geometry', struct('wheel_center', W_C(:)', 'tire_radius_m', R_tire, ...
        'arm_x_offset_m', arm_x_offset, 'source', axle.source), ...
    'symmetry_contract', struct( ...
        'mode', 'mirrored', ...
        'left_right_hardpoints', 'exact_y_mirror', ...
        'asymmetric_static_alignment_supported', true, ...
        'description', 'Left corner is optimized; right hardpoints are an exact Y mirror. Static toe/camber remain per-corner.'), ...
    'optimizer', 'MultiStart/fmincon/sqp', ...
    'solver_options', struct('Algorithm', 'sqp', 'StepTolerance', 1e-12, ...
        'ConstraintTolerance', 1e-6, 'MultiStartDisplay', 'iter', 'UseParallel', false), ...
    'code_version', get_code_version(project_matlab_dir), ...
    'n_starts', run_options.n_starts, ...
    'random_seed', run_options.rng_seed, ...
    'optimizer_cost', fval, ...
    'optimizer_exitflag', exitflag, ...
    'optimizer_diagnostics', struct( ...
        'local_exitflags', [ms_solutions.Exitflag], ...
        'n_local_starts', numel(ms_solutions), ...
        'n_local_converged', sum([ms_solutions.Exitflag] > 0), ...
        'elapsed_s', optimizer_elapsed_s, ...
        'evaluation_cache_entries', cache_count(cost_cache), ...
        'evaluation_cache_enabled', use_cache), ...
    'design_vector', x_opt(:)', ...
    'bounds_lb', lb, ...
    'bounds_ub', ub, ...
    'targets', struct( ...
        'roll_center_z_m', -target_RC_Z, ...
        'kpi_deg', target_KPI, ...
        'caster_deg', target_Caster, ...
        'camber_gain_rad_m', target_camber_gain, ...
        'scrub_radius_m', targets.scrub_radius_m, ...
        'mechanical_trail_m', targets.mechanical_trail_m, ...
        'roll_center_height_per_travel', -targets.roll_center_height_per_travel, ...
        'roll_center_height_per_roll', targets.roll_center_height_per_roll, ...
        'jacking_force_per_fy', targets.jacking_force_per_fy), ...
    'achieved', struct( ...
        'roll_center_z_m', -metrics_fl.roll_center_z, ...
        'kpi_deg', metrics_fl.kpi_deg, ...
        'caster_deg', metrics_fl.caster_deg, ...
        'camber_gain_rad_m', metrics_fl.camber_gain_rad_m, ...
        'scrub_radius_m', metrics_fl.scrub_radius_m, ...
        'mechanical_trail_m', metrics_fl.mechanical_trail_m, ...
        'roll_center_height_per_travel', -metrics_fl.roll_center_height_per_travel, ...
        'roll_center_height_per_roll', metrics_fl.roll_center_height_per_roll, ...
        'jacking_force_per_fy', metrics_fl.jacking_force_per_fy));

[~, final_cost_terms] = evaluate_inverse_cost(metrics_fl, targets, 'front');
stageResult = struct( ...
    'objective_value', fval, ...
    'cost_terms', final_cost_terms, ...
    'roll_center_z_m', -metrics_fl.roll_center_z, ...
    'kpi_deg', metrics_fl.kpi_deg, ...
    'caster_deg', metrics_fl.caster_deg, ...
    'scrub_radius_m', metrics_fl.scrub_radius_m, ...
    'mechanical_trail_m', metrics_fl.mechanical_trail_m, ...
    'camber_gain_rad_m', metrics_fl.camber_gain_rad_m);

rc_target = roll_center_frame(target_RC_Z);
rc_achieved = roll_center_frame(metrics_fl.roll_center_z);
target_values = rmfield(targets, {'weights', 'tolerances', 'weight_policy', 'sources', ...
    'source_quality', 'quality', 'fallback_fields', 'provisional', 'model_version', 'model_scope'});
suspensionGeometry.front.target_contract = struct( ...
    'targets', target_values, ...
    'weights', targets.weights, ...
    'tolerances', targets.tolerances, ...
    'weight_policy', targets.weight_policy, ...
    'sources', targets.sources, ...
    'source_quality', targets.source_quality, ...
    'quality', targets.quality, ...
    'fallback_fields', {targets.fallback_fields}, ...
    'provisional', targets.provisional, ...
    'model_version', targets.model_version, ...
    'model_scope', targets.model_scope);
suspensionGeometry.front.constraints = struct( ...
    'max_kpi_deg', 25.0, 'max_caster_deg', 10.0, 'units', 'deg', ...
    'min_arm_length_m', 0.080, 'max_arm_length_m', 0.450, ...
    'min_inboard_clearance_m', 0.030, 'wheel_envelope_margin_m', 0.020, ...
    'definition', 'KPI in Y-Z plane; caster in X-Z plane');
suspensionGeometry.front.targets = merge_nested_structs(suspensionGeometry.front.targets, rc_target);
suspensionGeometry.front.achieved = merge_nested_structs(suspensionGeometry.front.achieved, rc_achieved);
stageResult = merge_nested_structs(stageResult, rc_achieved);

save_suspension_geometry_artifact( ...
    'BaseArtifactPath', json_file, ...
    'InPlace', true, ...
    'CurrentParams', params_update, ...
    'SuspensionGeometry', suspensionGeometry, ...
    'StageName', 'suspension_geometry_front', ...
    'StageOptimizer', 'multistart_fmincon', ...
    'StageResult', stageResult);

fprintf('\nFront suspension geometry appended to %s\n', json_file);
end

function geom = build_geom(x, W_C, R_tire, static_camber_deg, is_left, is_front, arm_x_offset)
U_C_y = x(1); U_C_z = x(2);
L_C_y = x(3); L_C_z = x(4);
U_U_loc = [x(5); x(6); x(7)];
L_U_loc = [x(8); x(9); x(10)];

c = cosd(static_camber_deg);
s = sind(static_camber_deg);
R_camb = [1, 0, 0; 0, c, s; 0, -s, c];

U_U = W_C + R_camb * U_U_loc;
L_U = W_C + R_camb * L_U_loc;
U_F = [W_C(1) + arm_x_offset; U_C_y; U_C_z];
U_R = [W_C(1) - arm_x_offset; U_C_y; U_C_z];
L_F = [W_C(1) + arm_x_offset; L_C_y; L_C_z];
L_R = [W_C(1) - arm_x_offset; L_C_y; L_C_z];

geom = struct();
geom.U_F = U_F; geom.U_R = U_R; geom.U_U = U_U;
geom.L_F = L_F; geom.L_R = L_R; geom.L_U = L_U;
geom.W_C = W_C;
geom.R_tire = R_tire;
geom.is_left = is_left;
geom.is_front = is_front;
spindle_local = is_left * [0; -1; 0] + (~is_left) * [0; 1; 0];
geom.Spindle_Dir = R_camb * spindle_local;
geom.upper_arm_axis = (U_R - U_F) / norm(U_R - U_F);
geom.upper_arm_axis_origin = U_F;
geom.lower_arm_axis = (L_R - L_F) / norm(L_R - L_F);
geom.lower_arm_axis_origin = L_F;
geom.kingpin_axis.origin = L_U;
geom.kingpin_axis.direction = (U_U - L_U) / norm(U_U - L_U);
end

function geom = mirror_geom(geom)
geom = mirror_wishbone_geometry(geom);
end

function metrics = evaluate_metrics(geom, params, staticToe, staticCamber)
metrics = evaluate_double_wishbone_3d(geom, ...
    'TrackWidth', params.mass.track_f, ...
    'Wheelbase', params.mass.wheelbase, ...
    'CGHeight', params.mass.h_cg, ...
    'CGToAxle', params.mass.a, ...
    'BrakeBiasFront', params.brake.balance, ...
    'DriveBiasRear', 1.0, ... % RWD: all drive torque at the rear axle
    'StaticToe', staticToe, ...
    'StaticCamber', 0.0, ...
    'SteeringStiffness', params.steering.stiffness, ...
    'UseTieRod', false);
end

function cost = cost_function(x, params, targets, W_C, R_tire, max_upright_radius, min_kp_z_sep, arm_x_offset, cost_cache)
use_cache = isa(cost_cache, 'containers.Map');
cache_key = sprintf('%.12g|', x(:));
if use_cache && isKey(cost_cache, cache_key)
    cost = cost_cache(cache_key);
    return;
end
geom = build_geom(x, W_C, R_tire, rad2deg(params.suspension.static_camber(1)), true, true, arm_x_offset);
metrics = evaluate_metrics(geom, params, params.suspension.static_toe(1), params.suspension.static_camber(1));
[cost, ~] = evaluate_inverse_cost(metrics, targets, 'front');

if metrics.IC_y > 0
    cost = cost + 1e5;
end
if ~metrics.converged
    cost = cost + 1e10;
end
if use_cache
    cost_cache(cache_key) = cost;
end
end

function [c, ceq] = physical_constraints(x, W_C, R_tire, static_camber_deg, max_upright_radius, min_kp_z_sep, arm_x_offset)
geom = build_geom(x, W_C, R_tire, static_camber_deg, true, true, arm_x_offset);
max_kpi_tilt_deg = 25.0;
max_caster_tilt_deg = 10.0;
arm_clear_gap = 0.040;
min_arm_length = 0.080;
max_arm_length = 0.450;
[kpi_deg, caster_deg] = kingpin_angles((geom.L_U - geom.U_U) / norm(geom.L_U - geom.U_U));
max_upper_z = max(x(2), geom.U_U(3));
min_lower_z = min(x(4), geom.L_U(3));
upper_arm_length = norm(geom.U_U - (geom.U_F + geom.U_R) / 2);
lower_arm_length = norm(geom.L_U - (geom.L_F + geom.L_R) / 2);
upper_chassis_y = (geom.U_F(2) + geom.U_R(2)) / 2;
lower_chassis_y = (geom.L_F(2) + geom.L_R(2)) / 2;
if geom.is_left
    upper_inboard = upper_chassis_y - W_C(2);
    lower_inboard = lower_chassis_y - W_C(2);
else
    upper_inboard = W_C(2) - upper_chassis_y;
    lower_inboard = W_C(2) - lower_chassis_y;
end
min_inboard_clearance = 0.030;
wheel_envelope_margin = 0.020;
c = [ ...
    kpi_deg - max_kpi_tilt_deg; ...
    caster_deg - max_caster_tilt_deg; ...
    min_kp_z_sep - (geom.L_U(3) - geom.U_U(3)); ...
    (max_upper_z - min_lower_z) + arm_clear_gap; ...
    norm(x(5:7)) - max_upright_radius; ...
    norm(x(8:10)) - max_upright_radius; ...
    min_arm_length - upper_arm_length; ...
    upper_arm_length - max_arm_length; ...
    min_arm_length - lower_arm_length; ...
    lower_arm_length - max_arm_length; ...
    min_inboard_clearance - upper_inboard; ...
    min_inboard_clearance - lower_inboard; ...
    norm(geom.U_U - W_C) - (R_tire + wheel_envelope_margin); ...
    norm(geom.L_U - W_C) - (R_tire + wheel_envelope_margin) ...
];
ceq = [];
end

function axle = build_axle_kc(metrics, motionRatio, is_front)
% Runtime (14DOF) convention: roll_center_height is height above ground,
% derivatives are with respect to compression-positive suspension travel.
axle = struct();
axle.roll_center_height = -metrics.roll_center_z;
axle.roll_center_lateral = 0.0;
axle.roll_center_height_per_travel = -metrics.roll_center_height_per_travel;
axle.roll_center_height_per_roll = -metrics.roll_center_height_per_roll;
axle.anti_brake_pct = metrics.anti_brake_pct;
axle.anti_drive_pct = metrics.anti_drive_pct;
axle.anti_lift_pct = metrics.anti_lift_pct;
axle.anti_rise_pct = metrics.anti_rise_pct;
axle.anti_dive_pct = metrics.anti_dive_pct;
axle.anti_squat_pct = metrics.anti_squat_pct;
axle.anti_brake_vs_travel = metrics.anti_brake_vs_travel;
axle.anti_drive_vs_travel = metrics.anti_drive_vs_travel;
axle.anti_model = metrics.anti_model;
axle.anti_validated = metrics.anti_validated;
axle.arb_motion_ratio = mean(motionRatio(:));
if is_front
    axle.anti_rise_pct = 0.0;
    axle.anti_squat_pct = 0.0;
else
    axle.anti_lift_pct = 0.0;
    axle.anti_dive_pct = 0.0;
end
end

function corner = build_corner_kc(geom, metrics, staticToe, staticCamber)
% 14DOF roll angle phi > 0 compresses the right side. The local roll sweep
% drops the evaluated corner, so a left corner follows +phi and a right
% corner follows -phi. Jacking lifts one side and drops the other.
if geom.is_left
    side_factor = 1.0;
else
    side_factor = -1.0;
end
corner = struct();
corner.caster = deg2rad(metrics.caster_deg);
corner.kpi = deg2rad(metrics.kpi_deg);
corner.sai = deg2rad(metrics.kpi_deg);
corner.scrub_radius = metrics.scrub_radius_m;
corner.mechanical_trail = metrics.mechanical_trail_m;
corner.caster_trail = metrics.mechanical_trail_m;
corner.hardpoints = struct( ...
    'upper_arm_chassis_fore', reshape(geom.U_F, 1, []), ...
    'upper_arm_chassis_aft', reshape(geom.U_R, 1, []), ...
    'lower_arm_chassis_fore', reshape(geom.L_F, 1, []), ...
    'lower_arm_chassis_aft', reshape(geom.L_R, 1, []), ...
    'upper_ball_joint', reshape(geom.U_U, 1, []), ...
    'lower_ball_joint', reshape(geom.L_U, 1, []), ...
    'wheel_center', reshape(geom.W_C, 1, []), ...
    'contact_patch', reshape(metrics.contact_patch, 1, []));
corner.kinematics = struct( ...
    'camber_vs_travel', metrics.camber_vs_travel, ...
    'roll_camber_gain', side_factor * metrics.roll_camber_gain, ...
    'jacking_force_per_fy', -side_factor * metrics.jacking_force_per_fy);
corner.evaluation_scope = struct( ...
    'travel', 'evaluated', ...
    'roll', 'evaluated', ...
    'steering', 'not_evaluated', ...
    'tie_rod', 'not_evaluated', ...
    'toe', 'not_evaluated', ...
    'roll_steer', 'not_evaluated', ...
    'anti', 'proxy_not_validated', ...
    'jacking', 'proxy_not_validated', ...
    'compliance', 'proxy_not_validated');
corner.quality = struct( ...
    'verdict', 'provisional', ...
    'confidence', 'low', ...
    'reasons', {{'tie_rod_not_evaluated', 'a_arm_only_two_dof'}});
corner.source = struct( ...
    'model', 'a_arm_only_two_dof', ...
    'script', 'suspension_kinematics_design/main_a_arm_optimizer.m', ...
    'tie_rod_model', 'not_evaluated');
corner.compliance = metrics.compliance;
corner.proxy_metrics = {'anti_brake_pct', 'anti_drive_pct', 'anti_lift_pct', ...
    'anti_rise_pct', 'jacking_force_per_fy', 'compliance'};
corner.anti_metrics = struct('dive', metrics.anti_dive_pct, ...
    'squat', metrics.anti_squat_pct, 'lift', metrics.anti_lift_pct, ...
    'rise', metrics.anti_rise_pct, 'model', metrics.anti_model, ...
    'validated', metrics.anti_validated);
corner.proxy_sources = struct( ...
    'anti', metrics.anti_model, ...
    'jacking', metrics.jacking_model, ...
    'compliance', metrics.compliance_model);
corner.solver_status = metrics.solver_status;
corner.static_alignment = struct('toe', staticToe, 'camber', staticCamber);
end

function n = cache_count(cache)
if isempty(cache)
    n = 0;
else
    n = cache.Count;
end
end
