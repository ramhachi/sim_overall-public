classdef test_parallel_arm_roll_center < matlab.unittest.TestCase
    % Parallel upper/lower arms in front view put the IC at infinity along the
    % arms. The static sample must not collapse the RC to the ground (spike at
    % roll 0 / travel 0 that made the production front RC-vs-roll fit fail).
    methods (Test)
        function staticSampleIsContinuous(tc)
            addpath(fullfile(fileparts(mfilename('fullpath')), '..'));
            geom = geom_from_hardpoints(production_front_left_hardpoints(), ...
                true, true, -0.017, 0.22434118645161288);
            m = evaluate_double_wishbone_3d(geom, 'UseTieRod', true, 'TrackWidth', 1.2, ...
                'StaticToe', -0.002, 'StaticCamber', -0.017, ...
                'TravelSamples', [-0.01, 0, 0.01], 'SteerSamples', 0, ...
                'RackSamples', [-0.01, 0, 0.01], 'RollSamples', deg2rad(linspace(-4, 4, 9)));
            tc.verifyTrue(m.converged);
            rc = m.roll_center_curve;
            tc.verifyEqual(rc(5), m.roll_center_z, 'AbsTol', 1e-3);
            tc.verifyEqual(rc(5), mean(rc([4, 6])), 'AbsTol', 2e-3);
            tc.verifyEqual(m.lut_samples.rc_height_m(2), -m.roll_center_z, 'AbsTol', 1e-3);
            tc.verifyLessThan(m.polyfit_quality.rc_roll_max_error_m, 5e-3);
        end
    end
end

