function [cost, terms] = evaluate_inverse_cost(metrics, targets, axleKey)
% EVALUATE_INVERSE_COST Tolerance-normalized inverse-design objective.

tol = targets.tolerances;
w = targets.weights;
terms = struct();

terms.roll_center_z = normalized(metrics.roll_center_z, targets.roll_center_z, tol.roll_center_z);
terms.kpi = normalized(metrics.kpi_deg, targets.kpi_deg, tol.kpi_deg);
terms.caster = normalized(metrics.caster_deg, targets.caster_deg, tol.caster_deg);
terms.scrub = normalized(metrics.scrub_radius_m, targets.scrub_radius_m, tol.scrub_radius_m);
terms.mechanical_trail = normalized(metrics.mechanical_trail_m, targets.mechanical_trail_m, tol.mechanical_trail_m);
terms.camber_gain = normalized(metrics.camber_gain_rad_m, targets.camber_vs_travel(2), tol.camber_gain_rad_m);
terms.roll_camber_gain = normalized(metrics.roll_camber_gain, targets.roll_camber_gain, tol.roll_camber_gain);
terms.roll_center_height_per_travel = normalized(metrics.roll_center_height_per_travel, ...
    targets.roll_center_height_per_travel, tol.roll_center_height_per_travel);
terms.roll_center_height_per_roll = normalized(metrics.roll_center_height_per_roll, ...
    targets.roll_center_height_per_roll, tol.roll_center_height_per_roll);
terms.jacking = normalized(metrics.jacking_force_per_fy, targets.jacking_force_per_fy, tol.jacking_force_per_fy);

if strcmpi(axleKey, 'front')
    terms.anti = normalized(metrics.anti_brake_pct, targets.anti_brake_pct, tol.anti_pct);
else
    terms.anti = normalized(metrics.anti_drive_pct, targets.anti_drive_pct, tol.anti_pct);
end

terms.compliance = [ ...
    (metrics.compliance.camber_per_load(:) - targets.camber_per_load(:)) / tol.compliance; ...
    (metrics.compliance.toe_per_load(:) - targets.toe_per_load(:)) / tol.compliance];

cost = w.roll_center_z * terms.roll_center_z^2 ...
    + w.kpi * terms.kpi^2 ...
    + w.caster * terms.caster^2 ...
    + w.scrub * terms.scrub^2 ...
    + w.mechanical_trail * terms.mechanical_trail^2 ...
    + w.camber_gain * terms.camber_gain^2 ...
    + w.roll_camber_gain * terms.roll_camber_gain^2 ...
    + w.roll_center_migration * (terms.roll_center_height_per_travel^2 ...
        + terms.roll_center_height_per_roll^2) ...
    + w.jacking * terms.jacking^2 ...
    + w.anti * terms.anti^2 ...
    + w.compliance * sum(terms.compliance.^2);
end

function value = normalized(actual, target, tolerance)
value = (actual - target) / max(abs(tolerance), eps);
end
